def require_peer_version(local: str, peer: str, component: str) -> None:
    """Accept same-major peers; document-schema checks enforce required fields separately."""
    own = re.fullmatch(r"(0|[1-9]\d*)\.\d+\.\d+(?:[-+][0-9A-Za-z.+-]+)?", local)
    other = re.fullmatch(r"(0|[1-9]\d*)\.\d+\.\d+(?:[-+][0-9A-Za-z.+-]+)?", peer)
    expected = f">={own[1]}.0.0,<{int(own[1]) + 1}.0.0" if own else "MAJOR.MINOR.PATCH"
    if own is None or other is None or own[1] != other[1]:
        raise ConfigurationError(
            f"{component} version={peer}, local version={local}; expected {expected}; "
            f"upgrade {component} to a release in that range and restart it"
        )


def input_refusal(kind: InputKind, name: str) -> str:
    """Name a known introduction; unknown future inputs cannot name a future release."""
    introduced = INTRODUCED[kind].get(name)
    requirement = f" requires etl-craft {introduced};" if introduced else ";"
    return (
        f"etl-craft {__version__}: unsupported {kind} {name!r}{requirement} "
        "upgrade the component to a release that supports this input"
    )


