-- etl-craft: rebuild-metadata
-- Administrator-owned project routing and secret variable references.
CREATE TABLE CFG_ALERT_CHANNELS (
    CHANNEL_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    PROJECT_ID BIGINT NOT NULL REFERENCES CFG_PROJECTS(PROJECT_ID),
    CHANNEL_NAME VARCHAR NOT NULL,
    KIND VARCHAR NOT NULL CHECK (KIND IN ('WEBHOOK','SLACK')),
    URL_SECRET VARCHAR NOT NULL,
    SIGNING_SECRET VARCHAR NOT NULL,
    BODY_FORMAT VARCHAR NOT NULL CHECK (BODY_FORMAT IN ('JSON','SLACK')),
    DEFAULT_ALERT_ON VARCHAR,
    ACTIVE_FLAG VARCHAR NOT NULL DEFAULT 'Y' CHECK (ACTIVE_FLAG IN ('Y','N')),
    CREATED_BY VARCHAR NOT NULL DEFAULT 'etl-craft',
    CREATE_DATE TIMESTAMP NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%f', 'now') || '000+00:00'),
    UPDATED_BY VARCHAR NOT NULL DEFAULT 'etl-craft',
    UPDATED_DATE TIMESTAMP NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%f', 'now') || '000+00:00'),
    UNIQUE (PROJECT_ID, CHANNEL_NAME),
    CHECK (URL_SECRET GLOB '[A-Za-z_]*' AND URL_SECRET NOT GLOB '*[^A-Za-z0-9_]*'),
    CHECK (SIGNING_SECRET GLOB '[A-Za-z_]*' AND SIGNING_SECRET NOT GLOB '*[^A-Za-z0-9_]*'),
    CHECK ((KIND='WEBHOOK' AND BODY_FORMAT='JSON') OR (KIND='SLACK' AND BODY_FORMAT='SLACK'))
);
-- Immutable admission and delivery facts, without endpoint values or response bodies.
CREATE TABLE AUD_ALERT_DELIVERIES (
    DELIVERY_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    CHANNEL_ID BIGINT NOT NULL REFERENCES CFG_ALERT_CHANNELS(CHANNEL_ID),
    PIPELINE_RUN_ID BIGINT NOT NULL REFERENCES AUD_PIPELINES_RUN_LOG(PIPELINE_RUN_ID),
    SOURCE_RUN_ID BIGINT NOT NULL,
    SOURCE_TASK_ID BIGINT REFERENCES CFG_TASKS(TASK_ID),
    SOURCE_ATTEMPT_ID BIGINT,
    TASK_RUN_ID BIGINT REFERENCES AUD_TASK_RUN_LOG(TASK_RUN_ID),
    EVENT_ID VARCHAR NOT NULL,
    TRIGGER VARCHAR NOT NULL,
    ATTEMPT_NUMBER INTEGER NOT NULL CHECK (ATTEMPT_NUMBER BETWEEN 1 AND 4),
    STATUS VARCHAR NOT NULL CHECK (STATUS IN ('ADMITTED','STARTED','SENT','RETRY','FAILED')),
    STATUS_CODE INTEGER,
    ERROR_CLASS VARCHAR,
    CREATED_BY VARCHAR NOT NULL,
    CREATED_BY_KIND VARCHAR NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL
);
CREATE INDEX ix_alert_delivery_run ON AUD_ALERT_DELIVERIES(PIPELINE_RUN_ID,DELIVERY_ID);
CREATE INDEX ix_alert_delivery_source ON AUD_ALERT_DELIVERIES(SOURCE_RUN_ID,DELIVERY_ID);
CREATE INDEX ix_alert_delivery_event ON AUD_ALERT_DELIVERIES(CHANNEL_ID,EVENT_ID,ATTEMPT_NUMBER,DELIVERY_ID);
CREATE TRIGGER trg_actor_guard_aud_alert_deliveries_insert BEFORE INSERT ON AUD_ALERT_DELIVERIES
BEGIN SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT, 'AUD_ALERT_DELIVERIES is written only by etl-craft; use alert tasks') END; END;
CREATE TRIGGER trg_actor_guard_aud_alert_deliveries_update BEFORE UPDATE ON AUD_ALERT_DELIVERIES
BEGIN SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT, 'AUD_ALERT_DELIVERIES is written only by etl-craft; use alert tasks') END; END;
CREATE TRIGGER trg_actor_guard_aud_alert_deliveries_delete BEFORE DELETE ON AUD_ALERT_DELIVERIES
BEGIN SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT, 'AUD_ALERT_DELIVERIES is written only by etl-craft; use alert tasks') END; END;
CREATE TRIGGER trg_alert_delivery_immutable_update BEFORE UPDATE ON AUD_ALERT_DELIVERIES
BEGIN SELECT RAISE(ABORT, 'alert deliveries are append-only; inspect the alert run and retry it'); END;
CREATE TRIGGER trg_alert_delivery_immutable_delete BEFORE DELETE ON AUD_ALERT_DELIVERIES
WHEN etl_craft_purpose()<>'retention'
BEGIN SELECT RAISE(ABORT, 'alert deliveries are append-only; inspect the alert run and retry it'); END;

CREATE INDEX ix_alert_source_failure ON AUD_PIPELINES_RUN_LOG(PIPELINE_ID,PIPELINE_RUN_ID) WHERE STATUS='FAILED';
CREATE INDEX ix_alert_source_sla ON AUD_PIPELINES_RUN_LOG(PIPELINE_ID,PIPELINE_RUN_ID) WHERE SLA_STATUS='BREACHED';
CREATE INDEX ix_alert_lost_attempts ON AUD_TASK_ATTEMPTS(TASK_RUN_ID,ATTEMPT_ID) WHERE STATUS='LOST';
CREATE INDEX ix_alert_gate_waits ON AUD_GATE_WAITS(PIPELINE_RUN_ID,FIRST_CHECK_AT) WHERE NEXT_CHECK_AT IS NOT NULL;

-- Actor-attributed versions of administrator-owned channel definitions.
CREATE TABLE AUD_CFG_ALERT_CHANNELS_HISTORY (
 CHANGE_ID BIGINT PRIMARY KEY, VALID_FROM TIMESTAMP NOT NULL, VALID_TO TIMESTAMP NOT NULL,
 CURRENT_FLAG VARCHAR(1) NOT NULL, OPERATION VARCHAR NOT NULL, ACTOR VARCHAR NOT NULL,
 ACTOR_KIND VARCHAR NOT NULL, MIGRATION VARCHAR, CHANNEL_ID BIGINT, PROJECT_ID BIGINT,
 CHANNEL_NAME VARCHAR, KIND VARCHAR, URL_SECRET VARCHAR, SIGNING_SECRET VARCHAR,
 BODY_FORMAT VARCHAR, DEFAULT_ALERT_ON VARCHAR, ACTIVE_FLAG VARCHAR,
 CREATED_BY VARCHAR, CREATE_DATE TIMESTAMP, UPDATED_BY VARCHAR, UPDATED_DATE TIMESTAMP,
 UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_alert_channel_history_project ON AUD_CFG_ALERT_CHANNELS_HISTORY(PROJECT_ID,VALID_TO) WHERE CURRENT_FLAG='N';
CREATE UNIQUE INDEX ux_alert_run_admission ON AUD_ALERT_DELIVERIES(PIPELINE_RUN_ID) WHERE STATUS='ADMITTED';
CREATE UNIQUE INDEX ux_alert_event_admission ON AUD_ALERT_DELIVERIES(CHANNEL_ID,EVENT_ID) WHERE STATUS='ADMITTED';
