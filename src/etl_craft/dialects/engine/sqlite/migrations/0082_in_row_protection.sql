-- Hash-only write-ahead protection intents and immutable recovery outcomes.
CREATE TABLE AUD_PROTECTION_EVENTS (
 EVENT_ID INTEGER PRIMARY KEY AUTOINCREMENT,
 PROJECT_ID BIGINT NOT NULL REFERENCES CFG_PROJECTS(PROJECT_ID),
 TARGET_ID VARCHAR(512) NOT NULL,
 REQUEST_ID VARCHAR(36) NOT NULL,
 ATTEMPT_ID BIGINT,
 KIND VARCHAR(16) NOT NULL CHECK (KIND IN ('ENABLE','KEY','VERSION','SOFT_DELETE','WRITE','LOCK','UNLOCK','REHASH','HARD_DELETE','ERASURE')),
 KEY_CHECK VARCHAR(64) NOT NULL CHECK (length(KEY_CHECK)=64),
 KEY_HASH VARCHAR(64) CHECK (KEY_HASH IS NULL OR length(KEY_HASH)=64),
 COLUMN_NAMES TEXT NOT NULL,
 VALUE_HASHES TEXT NOT NULL,
 STATUS VARCHAR(16) NOT NULL CHECK (STATUS IN ('PENDING','COMMITTED','ABANDONED')),
 CREATED_BY VARCHAR(128) NOT NULL,
 CREATED_AT TIMESTAMP NOT NULL,
 RECOVERING_ATTEMPT_ID BIGINT,
 RECOVERY_ACTOR VARCHAR(128),
 UPLOAD_ID BIGINT REFERENCES AUD_UPLOADS(UPLOAD_ID),
 CHECK (UPLOAD_ID IS NULL OR KIND IN ('ENABLE','KEY','VERSION','WRITE','LOCK','UNLOCK')),
 CHECK ((STATUS='PENDING' AND KEY_HASH IS NOT NULL AND RECOVERY_ACTOR IS NULL AND RECOVERING_ATTEMPT_ID IS NULL)
 OR (STATUS<>'PENDING' AND KEY_HASH IS NULL)),
 CHECK (RECOVERING_ATTEMPT_ID IS NULL OR RECOVERY_ACTOR IS NOT NULL)
);
CREATE INDEX ix_privacy_erasure_tasks ON CFG_TASKS (PIPELINE_ID) WHERE HANDLER='ERASURE';
CREATE INDEX ix_protection_privacy ON AUD_PROTECTION_EVENTS (PROJECT_ID,KEY_CHECK);
CREATE INDEX ix_erasure_privacy ON AUD_ERASURE_SUBJECTS (PROJECT_ID,KEY_CHECK);
CREATE INDEX ix_protection_attempt ON AUD_PROTECTION_EVENTS (ATTEMPT_ID,PROJECT_ID,REQUEST_ID) WHERE STATUS='PENDING' AND ATTEMPT_ID IS NOT NULL;
CREATE INDEX ix_protection_request ON AUD_PROTECTION_EVENTS (PROJECT_ID,TARGET_ID,REQUEST_ID,EVENT_ID);
CREATE INDEX ix_protection_recovery ON AUD_PROTECTION_EVENTS (PROJECT_ID,TARGET_ID,STATUS,EVENT_ID);
CREATE INDEX ix_protection_keys ON AUD_PROTECTION_EVENTS (PROJECT_ID,TARGET_ID,KEY_HASH,EVENT_ID);
CREATE INDEX ix_protection_final_target ON AUD_PROTECTION_EVENTS (PROJECT_ID,TARGET_ID,EVENT_ID DESC,REQUEST_ID) WHERE STATUS<>'PENDING';
CREATE UNIQUE INDEX ux_protection_final ON AUD_PROTECTION_EVENTS (PROJECT_ID,REQUEST_ID) WHERE STATUS<>'PENDING';
CREATE TRIGGER trg_actor_guard_aud_protection_events_insert BEFORE INSERT ON AUD_PROTECTION_EVENTS
BEGIN
 SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT,'AUD_PROTECTION_EVENTS is written only by etl-craft') END;
END;
CREATE TRIGGER trg_actor_guard_aud_protection_events_update BEFORE UPDATE ON AUD_PROTECTION_EVENTS
BEGIN
 SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT,'AUD_PROTECTION_EVENTS is written only by etl-craft') END;
 SELECT RAISE(ABORT,'AUD_PROTECTION_EVENTS is append-only');
END;
CREATE TRIGGER trg_actor_guard_aud_protection_events_delete BEFORE DELETE ON AUD_PROTECTION_EVENTS
BEGIN
 SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT,'AUD_PROTECTION_EVENTS is written only by etl-craft') END;
 SELECT RAISE(ABORT,'AUD_PROTECTION_EVENTS is append-only');
END;

CREATE TRIGGER trg_privacy_check_aud_protection_events BEFORE INSERT ON AUD_PROTECTION_EVENTS
BEGIN
 SELECT CASE WHEN (COALESCE((SELECT MIN(KEY_CHECK) FROM AUD_PROTECTION_EVENTS WHERE PROJECT_ID=NEW.PROJECT_ID)<>NEW.KEY_CHECK,FALSE)
 OR COALESCE((SELECT MIN(KEY_CHECK) FROM AUD_ERASURE_SUBJECTS WHERE PROJECT_ID=NEW.PROJECT_ID)<>NEW.KEY_CHECK,FALSE)) THEN RAISE(ABORT,'Privacy.Hmac_secret differs from project history; restore the original secret') END;
END;
CREATE TRIGGER trg_privacy_check_aud_erasure_subjects BEFORE INSERT ON AUD_ERASURE_SUBJECTS
BEGIN
 SELECT CASE WHEN (COALESCE((SELECT MIN(KEY_CHECK) FROM AUD_PROTECTION_EVENTS WHERE PROJECT_ID=NEW.PROJECT_ID)<>NEW.KEY_CHECK,FALSE)
 OR COALESCE((SELECT MIN(KEY_CHECK) FROM AUD_ERASURE_SUBJECTS WHERE PROJECT_ID=NEW.PROJECT_ID)<>NEW.KEY_CHECK,FALSE)) THEN RAISE(ABORT,'Privacy.Hmac_secret differs from project history; restore the original secret') END;
END;
