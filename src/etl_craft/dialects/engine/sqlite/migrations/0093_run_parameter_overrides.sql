CREATE TABLE AUD_RUN_PARAMETER_OVERRIDES (
    PIPELINE_RUN_ID BIGINT PRIMARY KEY REFERENCES AUD_PIPELINES_RUN_LOG(PIPELINE_RUN_ID) ON DELETE CASCADE,
    PROJECT_ID BIGINT NOT NULL REFERENCES CFG_PROJECTS(PROJECT_ID),
    REQUEST_KEY VARCHAR(128),
    REQUEST_DIGEST VARCHAR(64) NOT NULL,
    OVERRIDES TEXT NOT NULL,
    CREATED_BY VARCHAR NOT NULL,
    CREATED_BY_KIND VARCHAR NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    UNIQUE (PROJECT_ID, REQUEST_KEY)
);
CREATE TRIGGER trg_actor_guard_aud_run_parameter_overrides_insert BEFORE INSERT ON AUD_RUN_PARAMETER_OVERRIDES
BEGIN SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT, 'AUD_RUN_PARAMETER_OVERRIDES is written only by etl-craft; use etl-craft run') END; END;
CREATE TRIGGER trg_actor_guard_aud_run_parameter_overrides_update BEFORE UPDATE ON AUD_RUN_PARAMETER_OVERRIDES
BEGIN SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT, 'AUD_RUN_PARAMETER_OVERRIDES is written only by etl-craft; use etl-craft run') END; END;
CREATE TRIGGER trg_actor_guard_aud_run_parameter_overrides_delete BEFORE DELETE ON AUD_RUN_PARAMETER_OVERRIDES
BEGIN SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT, 'AUD_RUN_PARAMETER_OVERRIDES is written only by etl-craft; use etl-craft run') END; END;
CREATE TRIGGER trg_run_overrides_update BEFORE UPDATE ON AUD_RUN_PARAMETER_OVERRIDES
BEGIN SELECT RAISE(ABORT, 'run parameter overrides are immutable; start a new run'); END;
CREATE TRIGGER trg_run_overrides_delete BEFORE DELETE ON AUD_RUN_PARAMETER_OVERRIDES
WHEN etl_craft_purpose() <> 'retention'
BEGIN SELECT RAISE(ABORT, 'run parameter overrides are immutable; start a new run'); END;
