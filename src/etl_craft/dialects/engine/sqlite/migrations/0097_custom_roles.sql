-- etl-craft: rebuild-metadata
-- Roles are named sets of actions. The four built-in roles keep the CAN_* meaning they had as
-- pipeline grant permissions; custom roles list their actions in CFG_ROLE_ACTIONS.
CREATE TABLE CFG_ROLES (
    ROLE_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    ROLE_NAME VARCHAR(64) NOT NULL UNIQUE CHECK (length(trim(ROLE_NAME)) BETWEEN 1 AND 64),
    DESCRIPTION TEXT,
    BUILT_IN_FLAG VARCHAR(1) NOT NULL DEFAULT 'N' CHECK (BUILT_IN_FLAG IN ('Y','N')),
    ACTIVE_FLAG VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (ACTIVE_FLAG IN ('Y','N')),
    CREATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    CREATE_DATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    UPDATED_DATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TRIGGER trg_cfg_roles_no_delete BEFORE DELETE ON CFG_ROLES
BEGIN SELECT RAISE(ABORT, 'CFG_ROLES: use ACTIVE_FLAG=N instead of deleting'); END;
INSERT INTO CFG_ROLES (ROLE_NAME,DESCRIPTION,BUILT_IN_FLAG) VALUES
('CAN_VIEW','Read pipelines, runs, logs and the catalog','Y'),
('CAN_UPLOAD','CAN_VIEW and upload stewarded files','Y'),
('CAN_RUN','CAN_UPLOAD and start, stop and recover runs','Y'),
('CAN_MANAGE','CAN_RUN and manage access and definitions','Y');

-- One action per row; ACTIVE_FLAG removes an action from a role without deleting history.
CREATE TABLE CFG_ROLE_ACTIONS (
    ROLE_ACTION_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    ROLE_ID BIGINT NOT NULL REFERENCES CFG_ROLES(ROLE_ID),
    ACTION_NAME VARCHAR(64) NOT NULL,
    ACTIVE_FLAG VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (ACTIVE_FLAG IN ('Y','N')),
    CREATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    CREATE_DATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    UPDATED_DATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX ux_role_action ON CFG_ROLE_ACTIONS (ROLE_ID, ACTION_NAME) WHERE ACTIVE_FLAG='Y';
CREATE TRIGGER trg_cfg_role_actions_no_delete BEFORE DELETE ON CFG_ROLE_ACTIONS
BEGIN SELECT RAISE(ABORT, 'CFG_ROLE_ACTIONS: use ACTIVE_FLAG=N instead of deleting'); END;

-- Every binding gives one principal (an account, a group, or every account with a deployment
-- role) one role or one action, on the deployment (no scope), one environment type, or one
-- project, optionally narrowed to a pipeline or a tag. Pipeline grants become bindings unchanged.
DROP VIEW IF EXISTS AUD_METADATA_CHANGES;
CREATE TABLE CFG_ACCESS_BINDINGS (
    BINDING_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    GROUP_ID BIGINT REFERENCES CFG_GROUPS(GROUP_ID),
    ACCOUNT_ID BIGINT REFERENCES CFG_ACCOUNTS(ACCOUNT_ID),
    GRANTEE_ROLE VARCHAR(16) CHECK (GRANTEE_ROLE IN ('viewer','operator','developer')),
    ROLE_NAME VARCHAR(64) REFERENCES CFG_ROLES(ROLE_NAME),
    ACTION_NAME VARCHAR(64),
    ENVIRONMENT_TYPE VARCHAR(16) CHECK (ENVIRONMENT_TYPE IN ('DEV','SIT','UAT','PROD','SANDBOX','CUSTOM')),
    PROJECT_ID BIGINT REFERENCES CFG_PROJECTS(PROJECT_ID),
    PIPELINE_CODE VARCHAR,
    TAG VARCHAR,
    ACTIVE_FLAG VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (ACTIVE_FLAG IN ('Y','N')),
    CREATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    CREATE_DATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    UPDATED_DATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (PROJECT_ID,PIPELINE_CODE) REFERENCES CFG_PIPELINES(PROJECT_ID,PIPELINE_CODE),
    CHECK ((CASE WHEN GROUP_ID IS NULL THEN 0 ELSE 1 END +
            CASE WHEN ACCOUNT_ID IS NULL THEN 0 ELSE 1 END +
            CASE WHEN GRANTEE_ROLE IS NULL THEN 0 ELSE 1 END)=1),
    CHECK ((ROLE_NAME IS NULL) <> (ACTION_NAME IS NULL)),
    CHECK (ENVIRONMENT_TYPE IS NULL OR PROJECT_ID IS NULL),
    CHECK (PROJECT_ID IS NOT NULL OR (PIPELINE_CODE IS NULL AND TAG IS NULL)),
    CHECK (PIPELINE_CODE IS NULL OR TAG IS NULL)
);
INSERT INTO CFG_ACCESS_BINDINGS (BINDING_ID,GROUP_ID,ACCOUNT_ID,GRANTEE_ROLE,ROLE_NAME,PROJECT_ID,PIPELINE_CODE,TAG,ACTIVE_FLAG,CREATED_BY,CREATE_DATE,UPDATED_BY,UPDATED_DATE)
SELECT PIPELINE_GRANT_ID,GROUP_ID,ACCOUNT_ID,GRANTEE_ROLE,PERMISSION,PROJECT_ID,PIPELINE_CODE,TAG,ACTIVE_FLAG,CREATED_BY,CREATE_DATE,UPDATED_BY,UPDATED_DATE FROM CFG_PIPELINE_GRANTS;
DROP TABLE CFG_PIPELINE_GRANTS;
CREATE INDEX ix_access_binding_project ON CFG_ACCESS_BINDINGS (PROJECT_ID) WHERE ACTIVE_FLAG='Y';
CREATE UNIQUE INDEX ux_access_builtin_level ON CFG_ACCESS_BINDINGS (
    COALESCE(ENVIRONMENT_TYPE,''), COALESCE(PROJECT_ID,0), COALESCE(PIPELINE_CODE,''), COALESCE(TAG,''),
    COALESCE(GROUP_ID,0), COALESCE(ACCOUNT_ID,0), COALESCE(GRANTEE_ROLE,'')
) WHERE ACTIVE_FLAG='Y' AND ROLE_NAME IN ('CAN_VIEW','CAN_UPLOAD','CAN_RUN','CAN_MANAGE');
CREATE UNIQUE INDEX ux_access_custom_binding ON CFG_ACCESS_BINDINGS (
    COALESCE(ENVIRONMENT_TYPE,''), COALESCE(PROJECT_ID,0), COALESCE(PIPELINE_CODE,''), COALESCE(TAG,''),
    COALESCE(GROUP_ID,0), COALESCE(ACCOUNT_ID,0), COALESCE(GRANTEE_ROLE,''),
    COALESCE(ROLE_NAME,''), COALESCE(ACTION_NAME,'')
) WHERE ACTIVE_FLAG='Y' AND (ACTION_NAME IS NOT NULL OR ROLE_NAME NOT IN ('CAN_VIEW','CAN_UPLOAD','CAN_RUN','CAN_MANAGE'));
CREATE TRIGGER trg_cfg_access_bindings_no_delete BEFORE DELETE ON CFG_ACCESS_BINDINGS
BEGIN SELECT RAISE(ABORT, 'CFG_ACCESS_BINDINGS: use ACTIVE_FLAG=N instead of deleting'); END;

