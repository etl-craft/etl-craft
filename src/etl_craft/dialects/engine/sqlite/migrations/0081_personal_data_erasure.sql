-- Standing, private erasure entries; only the one-way lift may change a row.
CREATE TABLE AUD_ERASURE_SUBJECTS (
 PROJECT_ID BIGINT NOT NULL REFERENCES CFG_PROJECTS(PROJECT_ID),
 TABLE_NAME VARCHAR(512) NOT NULL,
 COLUMN_NAME VARCHAR(128) NOT NULL,
 SUBJECT_KEY TEXT NOT NULL,
 KEY_HMAC VARCHAR(64) NOT NULL CHECK (length(KEY_HMAC)=64),
 ACTIVE_FLAG VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (ACTIVE_FLAG IN ('Y','N')),
 REASON TEXT NOT NULL CHECK (length(trim(REASON))>0),
 CREATED_BY VARCHAR NOT NULL,
 CREATED_AT TIMESTAMP NOT NULL,
 LIFTED_BY VARCHAR,
 LIFTED_AT TIMESTAMP,
 LIFT_REASON TEXT,
 PRIMARY KEY (PROJECT_ID,TABLE_NAME,COLUMN_NAME,KEY_HMAC,CREATED_AT),
 CHECK ((ACTIVE_FLAG='Y' AND LIFTED_BY IS NULL AND LIFTED_AT IS NULL AND LIFT_REASON IS NULL)
 OR (ACTIVE_FLAG='N' AND LIFTED_BY IS NOT NULL AND LIFTED_AT IS NOT NULL
 AND LIFT_REASON IS NOT NULL AND length(trim(LIFT_REASON))>0))
);
CREATE UNIQUE INDEX ux_erasure_active ON AUD_ERASURE_SUBJECTS
 (PROJECT_ID,TABLE_NAME,COLUMN_NAME,KEY_HMAC) WHERE ACTIVE_FLAG='Y';
CREATE INDEX ix_erasure_project_active ON AUD_ERASURE_SUBJECTS(PROJECT_ID,KEY_HMAC)
 WHERE ACTIVE_FLAG='Y';
CREATE TRIGGER trg_actor_guard_aud_erasure_subjects_insert BEFORE INSERT ON AUD_ERASURE_SUBJECTS
BEGIN
 SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT,'AUD_ERASURE_SUBJECTS is written only by etl-craft') END;
END;
CREATE TRIGGER trg_actor_guard_aud_erasure_subjects_update BEFORE UPDATE ON AUD_ERASURE_SUBJECTS
BEGIN
 SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT,'AUD_ERASURE_SUBJECTS is written only by etl-craft') END;
 SELECT CASE WHEN NOT (OLD.ACTIVE_FLAG='Y' AND NEW.ACTIVE_FLAG='N' AND NEW.PROJECT_ID IS OLD.PROJECT_ID AND NEW.TABLE_NAME IS OLD.TABLE_NAME AND NEW.COLUMN_NAME IS OLD.COLUMN_NAME AND NEW.SUBJECT_KEY IS OLD.SUBJECT_KEY AND NEW.KEY_HMAC IS OLD.KEY_HMAC AND NEW.REASON IS OLD.REASON AND NEW.CREATED_BY IS OLD.CREATED_BY AND NEW.CREATED_AT IS OLD.CREATED_AT) THEN RAISE(ABORT,'AUD_ERASURE_SUBJECTS permits only one lift; re-register a new entry') END;
END;
CREATE TRIGGER trg_actor_guard_aud_erasure_subjects_delete BEFORE DELETE ON AUD_ERASURE_SUBJECTS
BEGIN
 SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT,'AUD_ERASURE_SUBJECTS is written only by etl-craft') END;
 SELECT RAISE(ABORT,'AUD_ERASURE_SUBJECTS rows cannot be deleted; use erase --lift');
END;
