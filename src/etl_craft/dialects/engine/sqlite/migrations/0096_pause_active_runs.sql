-- Existing pipeline pauses retain FINISH, the dispatch behaviour under which they were created.
CREATE TEMP TABLE etl_craft_pause_preflight (
    holds_count BIGINT,
    wait_pauses_count BIGINT,
    CONSTRAINT "this Engine DB contains holds or wait pauses from an unreleased development build; recreate this development Engine DB" CHECK (holds_count=0 AND wait_pauses_count=0)
);
INSERT INTO etl_craft_pause_preflight SELECT
    (SELECT count(*) FROM AUD_CONTROL_REQUESTS WHERE ACTION IN ('HOLD','RELEASE')),
    (SELECT count(*) FROM AUD_PIPELINE_PAUSES WHERE TASK_ID IS NOT NULL AND OUTCOME IS NULL);
DROP TABLE etl_craft_pause_preflight;
CREATE TEMP TABLE etl_craft_control_sequence AS SELECT name,seq FROM sqlite_sequence WHERE name='AUD_CONTROL_REQUESTS';
CREATE TABLE AUD_CONTROL_REQUESTS_new (
    CONTROL_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    REQUEST_KEY VARCHAR(128) NOT NULL UNIQUE,
    PIPELINE_RUN_ID BIGINT NOT NULL REFERENCES AUD_PIPELINES_RUN_LOG(PIPELINE_RUN_ID),
    TASK_ID BIGINT REFERENCES CFG_TASKS(TASK_ID),
    ACTION VARCHAR(16) NOT NULL CONSTRAINT ck_control_action CHECK (ACTION IN ('STOP','ABORT','RECOVER','RESTART','RUN_PAUSED')),
    STATUS VARCHAR(16) NOT NULL CHECK (STATUS IN ('REQUESTED','ACKNOWLEDGED','COMPLETED')),
    ATTEMPT_IDS TEXT NOT NULL,
    REQUESTED_BY VARCHAR(128) NOT NULL,
    REQUESTED_BY_KIND VARCHAR(8) NOT NULL CHECK (REQUESTED_BY_KIND IN ('USER','SERVICE','SYSTEM')),
    REASON TEXT NOT NULL,
    REQUESTED_AT TIMESTAMP NOT NULL,
    ACKNOWLEDGED_AT TIMESTAMP,
    COMPLETED_AT TIMESTAMP,
    MESSAGE TEXT NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT '1970-01-01 00:00:00.000000+00:00'
);
INSERT INTO AUD_CONTROL_REQUESTS_new (CONTROL_ID,REQUEST_KEY,PIPELINE_RUN_ID,TASK_ID,ACTION,STATUS,ATTEMPT_IDS,REQUESTED_BY,REQUESTED_BY_KIND,REASON,REQUESTED_AT,ACKNOWLEDGED_AT,COMPLETED_AT,MESSAGE,UPDATED_AT) SELECT CONTROL_ID,REQUEST_KEY,PIPELINE_RUN_ID,TASK_ID,ACTION,STATUS,ATTEMPT_IDS,REQUESTED_BY,REQUESTED_BY_KIND,REASON,REQUESTED_AT,ACKNOWLEDGED_AT,COMPLETED_AT,MESSAGE,UPDATED_AT FROM AUD_CONTROL_REQUESTS;
DROP TABLE AUD_CONTROL_REQUESTS;
ALTER TABLE AUD_CONTROL_REQUESTS_new RENAME TO AUD_CONTROL_REQUESTS;
UPDATE sqlite_sequence SET seq=max(seq,coalesce((SELECT seq FROM etl_craft_control_sequence),seq)) WHERE name='AUD_CONTROL_REQUESTS';
INSERT INTO sqlite_sequence (name,seq) SELECT name,seq FROM etl_craft_control_sequence s WHERE NOT EXISTS (SELECT 1 FROM sqlite_sequence c WHERE c.name=s.name);
DROP TABLE etl_craft_control_sequence;
CREATE INDEX ix_control_scope ON AUD_CONTROL_REQUESTS (PIPELINE_RUN_ID,TASK_ID,CONTROL_ID);
CREATE INDEX ix_control_pending ON AUD_CONTROL_REQUESTS (PIPELINE_RUN_ID) WHERE STATUS <> 'COMPLETED';
CREATE TRIGGER trg_control_identity_update BEFORE UPDATE ON AUD_CONTROL_REQUESTS
WHEN OLD.STATUS='COMPLETED' OR NEW.CONTROL_ID IS NOT OLD.CONTROL_ID
OR NEW.REQUEST_KEY IS NOT OLD.REQUEST_KEY
OR NEW.PIPELINE_RUN_ID IS NOT OLD.PIPELINE_RUN_ID
OR NEW.TASK_ID IS NOT OLD.TASK_ID
OR NEW.ACTION IS NOT OLD.ACTION
OR NEW.ATTEMPT_IDS IS NOT OLD.ATTEMPT_IDS
OR NEW.REQUESTED_BY IS NOT OLD.REQUESTED_BY
OR NEW.REQUESTED_BY_KIND IS NOT OLD.REQUESTED_BY_KIND
OR NEW.REASON IS NOT OLD.REASON
OR NEW.REQUESTED_AT IS NOT OLD.REQUESTED_AT
BEGIN SELECT RAISE(ABORT, 'control request identity and completed outcome are immutable; submit a new control'); END;
CREATE TRIGGER trg_control_identity_delete BEFORE DELETE ON AUD_CONTROL_REQUESTS
WHEN etl_craft_purpose() <> 'retention'
BEGIN SELECT RAISE(ABORT, 'control request is immutable; use etl-craft retention'); END;

CREATE TEMP TABLE etl_craft_pipeline_pause_sequence AS SELECT name,seq FROM sqlite_sequence WHERE name='AUD_PIPELINE_PAUSES';
CREATE TABLE AUD_PIPELINE_PAUSES_new (
    PIPELINE_PAUSE_ID  INTEGER PRIMARY KEY AUTOINCREMENT,
    PIPELINE_ID        BIGINT NOT NULL REFERENCES CFG_PIPELINES(PIPELINE_ID),
    PAUSED_AT          TIMESTAMP NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%f', 'now') || '000+00:00'),
    PAUSED_BY          VARCHAR NOT NULL,
    REASON             VARCHAR NOT NULL,
    RESUMED_AT         TIMESTAMP,
    RESUMED_BY         VARCHAR,
    RESUME_REASON      VARCHAR,
    PAUSED_BY_KIND VARCHAR DEFAULT (etl_craft_actor_kind()) CONSTRAINT ck_aud_pipeline_pauses_paused_by_kind CHECK (PAUSED_BY_KIND IN ('USER','SERVICE','SYSTEM','HUMAN','SCHEDULE','ORCHESTRATOR','WORKER')),
    RESUMED_BY_KIND VARCHAR CONSTRAINT ck_aud_pipeline_pauses_resumed_by_kind CHECK (RESUMED_BY_KIND IN ('USER','SERVICE','SYSTEM','HUMAN','SCHEDULE','ORCHESTRATOR','WORKER')),
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT '1970-01-01 00:00:00.000000+00:00',
    TASK_ID BIGINT REFERENCES CFG_TASKS(TASK_ID),
    OUTCOME VARCHAR(16),
    EXPIRES_AT TIMESTAMP,
    ACTIVE_RUNS VARCHAR(8),
    CONSTRAINT ck_pause_scope CHECK ((TASK_ID IS NULL AND OUTCOME IS NULL AND ACTIVE_RUNS IS NOT NULL AND ACTIVE_RUNS IN ('DRAIN','FINISH')) OR (TASK_ID IS NOT NULL AND ACTIVE_RUNS IS NULL AND OUTCOME IS NOT NULL AND OUTCOME IN ('SUCCESS','FAILED','SKIPPED')))
);
INSERT INTO AUD_PIPELINE_PAUSES_new (PIPELINE_PAUSE_ID,PIPELINE_ID,PAUSED_AT,PAUSED_BY,REASON,RESUMED_AT,RESUMED_BY,RESUME_REASON,PAUSED_BY_KIND,RESUMED_BY_KIND,UPDATED_AT,TASK_ID,OUTCOME,EXPIRES_AT,ACTIVE_RUNS)
SELECT PIPELINE_PAUSE_ID,PIPELINE_ID,PAUSED_AT,PAUSED_BY,REASON,RESUMED_AT,RESUMED_BY,RESUME_REASON,PAUSED_BY_KIND,RESUMED_BY_KIND,UPDATED_AT,TASK_ID,OUTCOME,EXPIRES_AT,CASE WHEN TASK_ID IS NULL THEN 'FINISH' ELSE NULL END FROM AUD_PIPELINE_PAUSES;
DROP TABLE AUD_PIPELINE_PAUSES;
ALTER TABLE AUD_PIPELINE_PAUSES_new RENAME TO AUD_PIPELINE_PAUSES;
UPDATE sqlite_sequence SET seq=max(seq,coalesce((SELECT seq FROM etl_craft_pipeline_pause_sequence),seq)) WHERE name='AUD_PIPELINE_PAUSES';
INSERT INTO sqlite_sequence (name,seq) SELECT name,seq FROM etl_craft_pipeline_pause_sequence s WHERE NOT EXISTS (SELECT 1 FROM sqlite_sequence c WHERE c.name=s.name);
DROP TABLE etl_craft_pipeline_pause_sequence;
CREATE UNIQUE INDEX ux_pipeline_pauses_open ON AUD_PIPELINE_PAUSES (PIPELINE_ID) WHERE RESUMED_AT IS NULL AND TASK_ID IS NULL;
CREATE UNIQUE INDEX ux_task_pauses_open ON AUD_PIPELINE_PAUSES (TASK_ID) WHERE RESUMED_AT IS NULL AND TASK_ID IS NOT NULL;
CREATE INDEX ix_task_pauses_versions ON AUD_PIPELINE_PAUSES (TASK_ID,PIPELINE_PAUSE_ID);
CREATE INDEX ix_pause_identity_text ON AUD_PIPELINE_PAUSES ((CAST(PIPELINE_PAUSE_ID AS varchar)));
CREATE INDEX ix_pause_history ON AUD_PIPELINE_PAUSES (PIPELINE_ID,RESUMED_AT DESC);
CREATE INDEX ix_pipeline_pause_resume ON AUD_PIPELINE_PAUSES (PIPELINE_ID,RESUMED_AT DESC) WHERE TASK_ID IS NULL AND RESUMED_AT IS NOT NULL;
CREATE INDEX ix_pause_retention ON AUD_PIPELINE_PAUSES (COALESCE(RESUMED_AT,EXPIRES_AT),PIPELINE_PAUSE_ID);
