-- etl-craft: rebuild-metadata
-- A restart is a trigger kind of its own: widen ck_pipeline_run_trigger_kind to admit RESTART.
-- SQLite cannot alter a CHECK, so the run log is rebuilt with every column, index and trigger.
CREATE TEMP TABLE etl_craft_trigger_sequence AS SELECT name, seq FROM sqlite_sequence WHERE name='AUD_PIPELINES_RUN_LOG';
CREATE TABLE AUD_PIPELINES_RUN_LOG_new (
    PIPELINE_RUN_ID  INTEGER PRIMARY KEY AUTOINCREMENT,
    PIPELINE_ID      BIGINT NOT NULL REFERENCES CFG_PIPELINES(PIPELINE_ID),
    START_DATE       TIMESTAMP NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%f', 'now') || '000+00:00'),
    END_DATE         TIMESTAMP,
    STATUS           VARCHAR NOT NULL,
    SLA_STATUS       VARCHAR(8),
    RUN_DATE         DATE,
    BACKFILL         VARCHAR(1) NOT NULL DEFAULT 'N',
    RUN_KEY          VARCHAR NOT NULL DEFAULT ('manual:' || lower(hex(randomblob(16)))),
    TRIGGER_KIND     VARCHAR NOT NULL DEFAULT 'MANUAL',
    OWNER_ID         VARCHAR,
    LEASE_EXPIRES_AT TIMESTAMP,
    OUTPUT_REVISION  INT NOT NULL DEFAULT 1,
    CONFIG_SHA256    VARCHAR(64),
    STARTED_BY VARCHAR DEFAULT (etl_craft_actor()),
    STARTED_BY_KIND VARCHAR DEFAULT (etl_craft_actor_kind()) CONSTRAINT ck_aud_pipelines_run_log_started_by_kind CHECK (STARTED_BY_KIND IN ('USER','SERVICE','SYSTEM','HUMAN','SCHEDULE','ORCHESTRATOR','WORKER')),
    ENDED_BY VARCHAR,
    ENDED_BY_KIND VARCHAR CONSTRAINT ck_aud_pipelines_run_log_ended_by_kind CHECK (ENDED_BY_KIND IN ('USER','SERVICE','SYSTEM','HUMAN','SCHEDULE','ORCHESTRATOR','WORKER')),
    REPAIR_PENDING   VARCHAR NOT NULL DEFAULT 'N' CONSTRAINT ck_run_repair_pending CHECK (REPAIR_PENDING IN ('Y','N')),
    WRITER VARCHAR(128) NOT NULL DEFAULT 'etl-craft' CONSTRAINT ck_run_writer CHECK (length(trim(WRITER)) BETWEEN 1 AND 128),
    TASK_SELECTION   TEXT,
    EXCLUSIVE_RUN    VARCHAR(1) NOT NULL DEFAULT 'Y' CONSTRAINT ck_run_exclusive CHECK (EXCLUSIVE_RUN IN ('Y','N') AND (EXCLUSIVE_RUN='Y' OR TASK_SELECTION IS NOT NULL)),
    TRIGGERED_BY_TASK_RUN_ID BIGINT REFERENCES AUD_TASK_RUN_LOG(TASK_RUN_ID),
    SSO_GROUP_IDS TEXT NOT NULL DEFAULT '[]',
    BUNDLE_ID VARCHAR(64) REFERENCES AUD_PROJECT_BUNDLES(BUNDLE_ID),
    METADATA_VERSION VARCHAR(64),
    METADATA_SNAPSHOT TEXT,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT '1970-01-01 00:00:00.000000+00:00',
    SLA_BREACHED_AT TIMESTAMP,
    RUN_LABEL VARCHAR NOT NULL DEFAULT '',
    CONSTRAINT ck_pipeline_run_trigger_kind CHECK (TRIGGER_KIND IN ('SCHEDULE','MANUAL','BACKFILL','ORCHESTRATOR','STAND_IN','PIPELINE_TASK','RESTART')),
    CONSTRAINT ck_pipeline_run_backfill CHECK (BACKFILL IN ('Y','N')),
    CONSTRAINT ck_pipeline_run_status CHECK (STATUS IN ('QUEUED','IN-PROGRESS','SUCCESS','FAILED','SKIPPED','CANCELLED')),
    CONSTRAINT ck_pipeline_run_sla_status CHECK (SLA_STATUS IN ('MET','BREACHED'))
);
INSERT INTO AUD_PIPELINES_RUN_LOG_new (PIPELINE_RUN_ID, PIPELINE_ID, START_DATE, END_DATE, STATUS, SLA_STATUS, RUN_DATE, BACKFILL, RUN_KEY, TRIGGER_KIND, OWNER_ID, LEASE_EXPIRES_AT, OUTPUT_REVISION, CONFIG_SHA256, STARTED_BY, STARTED_BY_KIND, ENDED_BY, ENDED_BY_KIND, REPAIR_PENDING, WRITER, TASK_SELECTION, EXCLUSIVE_RUN, TRIGGERED_BY_TASK_RUN_ID, SSO_GROUP_IDS, BUNDLE_ID, METADATA_VERSION, METADATA_SNAPSHOT, UPDATED_AT, SLA_BREACHED_AT, RUN_LABEL) SELECT PIPELINE_RUN_ID, PIPELINE_ID, START_DATE, END_DATE, STATUS, SLA_STATUS, RUN_DATE, BACKFILL, RUN_KEY, TRIGGER_KIND, OWNER_ID, LEASE_EXPIRES_AT, OUTPUT_REVISION, CONFIG_SHA256, STARTED_BY, STARTED_BY_KIND, ENDED_BY, ENDED_BY_KIND, REPAIR_PENDING, WRITER, TASK_SELECTION, EXCLUSIVE_RUN, TRIGGERED_BY_TASK_RUN_ID, SSO_GROUP_IDS, BUNDLE_ID, METADATA_VERSION, METADATA_SNAPSHOT, UPDATED_AT, SLA_BREACHED_AT, RUN_LABEL FROM AUD_PIPELINES_RUN_LOG;
DROP TABLE AUD_PIPELINES_RUN_LOG;
ALTER TABLE AUD_PIPELINES_RUN_LOG_new RENAME TO AUD_PIPELINES_RUN_LOG;
UPDATE sqlite_sequence SET seq=max(seq, coalesce((SELECT seq FROM etl_craft_trigger_sequence), seq)) WHERE name='AUD_PIPELINES_RUN_LOG';
INSERT INTO sqlite_sequence (name, seq) SELECT name, seq FROM etl_craft_trigger_sequence s WHERE NOT EXISTS (SELECT 1 FROM sqlite_sequence c WHERE c.name=s.name);
DROP TABLE etl_craft_trigger_sequence;
CREATE UNIQUE INDEX ux_pipeline_run_one_active
    ON AUD_PIPELINES_RUN_LOG (PIPELINE_ID) WHERE STATUS = 'IN-PROGRESS' AND EXCLUSIVE_RUN='Y';
CREATE INDEX ix_catalog_pipeline_runs ON AUD_PIPELINES_RUN_LOG (PIPELINE_ID, PIPELINE_RUN_ID DESC);
CREATE UNIQUE INDEX ux_pipeline_run_key ON AUD_PIPELINES_RUN_LOG (PIPELINE_ID, RUN_KEY);
CREATE INDEX ix_run_trigger_task ON AUD_PIPELINES_RUN_LOG (TRIGGERED_BY_TASK_RUN_ID);
CREATE INDEX ix_pipeline_schedule_key ON AUD_PIPELINES_RUN_LOG (PIPELINE_ID, RUN_KEY) WHERE TRIGGER_KIND = 'SCHEDULE';
CREATE INDEX ix_pipeline_runs_pending ON AUD_PIPELINES_RUN_LOG (PIPELINE_ID, PIPELINE_RUN_ID)
    WHERE STATUS IN ('QUEUED', 'IN-PROGRESS');
CREATE INDEX ix_pipeline_runs_retention ON AUD_PIPELINES_RUN_LOG (PIPELINE_ID, START_DATE);
CREATE INDEX ix_metrics_runs ON AUD_PIPELINES_RUN_LOG (STATUS,PIPELINE_ID,PIPELINE_RUN_ID)
WHERE STATUS IN ('QUEUED','IN-PROGRESS');
CREATE INDEX ix_pipeline_run_bundle ON AUD_PIPELINES_RUN_LOG(BUNDLE_ID);
CREATE INDEX ix_project_health_runs_end ON AUD_PIPELINES_RUN_LOG (END_DATE,PIPELINE_ID) WHERE END_DATE IS NOT NULL;
CREATE INDEX ix_project_health_running ON AUD_PIPELINES_RUN_LOG (PIPELINE_ID) WHERE STATUS='IN-PROGRESS';
CREATE INDEX ix_seed_successful_runs ON AUD_PIPELINES_RUN_LOG(END_DATE,PIPELINE_RUN_ID)
WHERE STATUS='SUCCESS' AND END_DATE IS NOT NULL;
CREATE TRIGGER trg_actor_guard_aud_pipelines_run_log_insert BEFORE INSERT ON AUD_PIPELINES_RUN_LOG
BEGIN
    SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT, 'AUD_PIPELINES_RUN_LOG is written only by etl-craft; use etl-craft mark, cancel or run, or a project migration (etl-craft migrate)') END;
END;
CREATE TRIGGER trg_actor_guard_aud_pipelines_run_log_update BEFORE UPDATE ON AUD_PIPELINES_RUN_LOG
BEGIN
    SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT, 'AUD_PIPELINES_RUN_LOG is written only by etl-craft; use etl-craft mark, cancel or run, or a project migration (etl-craft migrate)') END;
END;
CREATE TRIGGER trg_actor_guard_aud_pipelines_run_log_delete BEFORE DELETE ON AUD_PIPELINES_RUN_LOG
BEGIN
    SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT, 'AUD_PIPELINES_RUN_LOG is written only by etl-craft; use etl-craft mark, cancel or run, or a project migration (etl-craft migrate)') END;
END;
CREATE TRIGGER trg_attribute_run_insert AFTER INSERT ON AUD_PIPELINES_RUN_LOG
BEGIN
    UPDATE AUD_PIPELINES_RUN_LOG SET STARTED_BY=COALESCE(NEW.STARTED_BY, etl_craft_actor()), STARTED_BY_KIND=COALESCE(NEW.STARTED_BY_KIND, etl_craft_actor_kind()), ENDED_BY=CASE WHEN NEW.END_DATE IS NOT NULL THEN COALESCE(NEW.ENDED_BY, etl_craft_actor()) ELSE NEW.ENDED_BY END, ENDED_BY_KIND=CASE WHEN NEW.END_DATE IS NOT NULL THEN COALESCE(NEW.ENDED_BY_KIND, etl_craft_actor_kind()) ELSE NEW.ENDED_BY_KIND END WHERE PIPELINE_RUN_ID=NEW.PIPELINE_RUN_ID;
END;
CREATE TRIGGER trg_run_definition_immutable BEFORE UPDATE OF BUNDLE_ID,METADATA_VERSION,METADATA_SNAPSHOT ON AUD_PIPELINES_RUN_LOG
WHEN OLD.METADATA_SNAPSHOT IS NOT NULL AND (NEW.BUNDLE_ID IS NOT OLD.BUNDLE_ID OR NEW.METADATA_VERSION IS NOT OLD.METADATA_VERSION OR NEW.METADATA_SNAPSHOT IS NOT OLD.METADATA_SNAPSHOT)
BEGIN SELECT RAISE(ABORT, 'run definition is immutable; start a new run'); END;
CREATE TRIGGER trg_run_label_aud_pipelines_run_log AFTER INSERT ON AUD_PIPELINES_RUN_LOG
BEGIN
    UPDATE AUD_PIPELINES_RUN_LOG SET RUN_LABEL =
        (SELECT p.PIPELINE_CODE FROM CFG_PIPELINES p WHERE p.PIPELINE_ID = NEW.PIPELINE_ID)
        || '-' || substr(NEW.START_DATE, 1, 19) || '-' || NEW.PIPELINE_RUN_ID
    WHERE PIPELINE_RUN_ID = NEW.PIPELINE_RUN_ID;
END;
