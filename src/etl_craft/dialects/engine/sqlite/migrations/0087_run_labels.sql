-- A readable identifier beside each integer run id, written once when the run is created.
ALTER TABLE AUD_PIPELINES_RUN_LOG ADD COLUMN RUN_LABEL VARCHAR NOT NULL DEFAULT '';
ALTER TABLE AUD_TASK_RUN_LOG ADD COLUMN TASK_RUN_LABEL VARCHAR NOT NULL DEFAULT '';
UPDATE AUD_PIPELINES_RUN_LOG SET RUN_LABEL =
    (SELECT p.PIPELINE_CODE FROM CFG_PIPELINES p WHERE p.PIPELINE_ID = AUD_PIPELINES_RUN_LOG.PIPELINE_ID)
    || '-' || substr(START_DATE, 1, 19) || '-' || PIPELINE_RUN_ID;
UPDATE AUD_TASK_RUN_LOG SET TASK_RUN_LABEL =
    (SELECT p.PIPELINE_CODE || '-' || t.TASK_CODE FROM CFG_TASKS t JOIN CFG_PIPELINES p ON p.PIPELINE_ID = t.PIPELINE_ID
     WHERE t.TASK_ID = AUD_TASK_RUN_LOG.TASK_ID)
    || '-' || substr(START_DATE, 1, 19) || '-' || TASK_RUN_ID;

-- The label is set by the database when the row is inserted, so every insert path names a run.
CREATE TRIGGER trg_run_label_aud_pipelines_run_log AFTER INSERT ON AUD_PIPELINES_RUN_LOG
BEGIN
    UPDATE AUD_PIPELINES_RUN_LOG SET RUN_LABEL =
        (SELECT p.PIPELINE_CODE FROM CFG_PIPELINES p WHERE p.PIPELINE_ID = NEW.PIPELINE_ID)
        || '-' || substr(NEW.START_DATE, 1, 19) || '-' || NEW.PIPELINE_RUN_ID
    WHERE PIPELINE_RUN_ID = NEW.PIPELINE_RUN_ID;
END;
CREATE TRIGGER trg_run_label_aud_task_run_log AFTER INSERT ON AUD_TASK_RUN_LOG
BEGIN
    UPDATE AUD_TASK_RUN_LOG SET TASK_RUN_LABEL =
        (SELECT p.PIPELINE_CODE || '-' || t.TASK_CODE FROM CFG_TASKS t JOIN CFG_PIPELINES p ON p.PIPELINE_ID = t.PIPELINE_ID
         WHERE t.TASK_ID = NEW.TASK_ID)
        || '-' || substr(NEW.START_DATE, 1, 19) || '-' || NEW.TASK_RUN_ID
    WHERE TASK_RUN_ID = NEW.TASK_RUN_ID;
END;
