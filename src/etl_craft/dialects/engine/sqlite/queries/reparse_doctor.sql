SELECT p.PIPELINE_CODE AS pipeline_code,r.STATUS AS status,r.FINDINGS AS findings,
p.BLOCK_ON_REPARSE_ERROR AS block_on_reparse_error,
EXISTS(SELECT 1 FROM AUD_PIPELINE_REPARSES good WHERE good.PIPELINE_ID=p.PIPELINE_ID AND good.STATUS='SUCCESS') AS has_baseline
FROM CFG_PIPELINES p
LEFT JOIN AUD_PIPELINE_REPARSES r ON r.REPARSE_ID=(SELECT MAX(latest.REPARSE_ID) FROM AUD_PIPELINE_REPARSES latest WHERE latest.PIPELINE_ID=p.PIPELINE_ID)
WHERE p.PROJECT_ID=:project_id AND p.ACTIVE_FLAG='Y' AND (r.STATUS='FAILED' OR r.REPARSE_ID IS NULL)
ORDER BY p.PIPELINE_CODE
