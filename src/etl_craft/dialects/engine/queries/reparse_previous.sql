SELECT r.REPARSED_AT AS reparsed_at,r.STATUS AS status,
COALESCE(r.METADATA_SNAPSHOT,s.METADATA_SNAPSHOT) AS snapshot,r.BUNDLE_ID AS bundle_id
FROM AUD_PIPELINE_REPARSES r
LEFT JOIN AUD_PIPELINE_REPARSES s ON s.REPARSE_ID=r.SNAPSHOT_REPARSE_ID
WHERE r.PIPELINE_ID=:pipeline_id
ORDER BY r.REPARSE_ID DESC LIMIT 1
