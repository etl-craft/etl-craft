SELECT t.TASK_CODE AS task_code, a.ATTEMPT_NUMBER AS attempt_number, a.STATUS AS status,
a.QUEUED_AT AS queued_at, a.STARTED_AT AS started_at, a.ENDED_AT AS ended_at
FROM AUD_TASK_RUN_LOG r
JOIN AUD_TASK_ATTEMPTS a ON a.TASK_RUN_ID=r.TASK_RUN_ID
JOIN CFG_TASKS t ON t.TASK_ID=r.TASK_ID
WHERE r.PIPELINE_RUN_ID=:run_id
ORDER BY a.TASK_RUN_ID, a.ATTEMPT_NUMBER
