SELECT e.KEY_HASH AS key_hash,e.COLUMN_NAMES AS column_names,e.KIND AS kind,e.EVENT_ID AS event_id
FROM AUD_PROTECTION_EVENTS e WHERE e.PROJECT_ID=:project_id AND e.TARGET_ID=:target
 AND e.KEY_HASH IS NOT NULL AND e.KIND IN ('KEY','LOCK','UNLOCK','HARD_DELETE','ERASURE')
 AND EXISTS (SELECT 1 FROM AUD_PROTECTION_EVENTS f WHERE f.PROJECT_ID=e.PROJECT_ID
 AND f.REQUEST_ID=e.REQUEST_ID AND f.STATUS='COMMITTED') ORDER BY e.EVENT_ID
