SELECT u.UPLOAD_ID AS upload_id,u.ACCOUNT AS uploader FROM AUD_UPLOADS u
WHERE u.UPLOAD_ID=:upload_id AND u.PIPELINE_RUN_ID=:pipeline_run_id AND u.STATUS<>'REFUSED'
AND EXISTS (SELECT 1 AS validated FROM AUD_TASK_RUN_LOG t
WHERE t.TASK_ID=:validator_id AND t.PIPELINE_RUN_ID=u.PIPELINE_RUN_ID AND t.STATUS='SUCCESS'
AND EXISTS (SELECT 1 AS genuine FROM AUD_TASK_ATTEMPTS a
WHERE a.TASK_RUN_ID=t.TASK_RUN_ID AND a.STATUS='SUCCESS'))
