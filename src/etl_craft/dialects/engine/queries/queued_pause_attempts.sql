SELECT a.ATTEMPT_ID AS attempt_id FROM AUD_TASK_ATTEMPTS a
JOIN AUD_TASK_RUN_LOG t ON t.TASK_RUN_ID=a.TASK_RUN_ID
JOIN AUD_PIPELINES_RUN_LOG p ON p.PIPELINE_RUN_ID=t.PIPELINE_RUN_ID
WHERE a.STATUS='QUEUED' AND a.OWNER_ID IS NULL AND a.POOL=:pool
AND p.PIPELINE_ID IN :pipeline_ids
AND EXISTS (SELECT 1 FROM AUD_PIPELINE_PAUSES pause WHERE pause.TASK_ID=t.TASK_ID
 AND pause.RESUMED_AT IS NULL) ORDER BY a.ATTEMPT_ID
