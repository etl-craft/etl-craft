SELECT p.PIPELINE_ID AS pipeline_id,r.PIPELINE_RUN_ID AS pipeline_run_id,r.RUN_LABEL AS run_label,r.STATUS AS status
FROM AUD_PIPELINES_RUN_LOG r JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID
JOIN AUD_PIPELINE_PAUSES pause ON pause.PIPELINE_ID=p.PIPELINE_ID
WHERE (:pipeline_id IS NULL OR p.PIPELINE_ID=:pipeline_id)
AND p.PROJECT_ID=:project_id AND pause.TASK_ID IS NULL AND pause.RESUMED_AT IS NULL
AND pause.ACTIVE_RUNS='DRAIN' AND r.STATUS IN ('QUEUED','IN-PROGRESS')
AND NOT EXISTS (SELECT 1 FROM AUD_ALERT_DELIVERIES a WHERE a.PIPELINE_RUN_ID=r.PIPELINE_RUN_ID AND a.STATUS='ADMITTED')
AND NOT EXISTS (SELECT 1 FROM AUD_CONTROL_REQUESTS c WHERE c.PIPELINE_RUN_ID=r.PIPELINE_RUN_ID AND c.ACTION='RUN_PAUSED')
ORDER BY r.PIPELINE_RUN_ID
