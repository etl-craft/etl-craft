WITH fences AS (
SELECT c.CONTROL_ID AS control_id, c.ACTION AS action, c.TASK_ID AS task_id
FROM AUD_CONTROL_REQUESTS c WHERE c.PIPELINE_RUN_ID=:run_id
AND c.ACTION IN ('STOP','ABORT')
AND NOT EXISTS (SELECT 1 FROM AUD_CONTROL_REQUESTS newer
WHERE newer.PIPELINE_RUN_ID=c.PIPELINE_RUN_ID AND newer.CONTROL_ID>c.CONTROL_ID
AND newer.ACTION IN ('STOP','ABORT','RECOVER')
AND (newer.TASK_ID=c.TASK_ID OR (newer.TASK_ID IS NULL AND c.TASK_ID IS NULL)))
)
SELECT r.PIPELINE_ID AS pipeline_id, c.CONTROL_ID AS control_id, c.ACTION AS action, c.TASK_ID AS task_id,
EXISTS (SELECT 1 FROM AUD_PIPELINE_PAUSES p WHERE p.PIPELINE_ID=r.PIPELINE_ID
 AND p.TASK_ID IS NULL AND p.RESUMED_AT IS NULL AND p.ACTIVE_RUNS='DRAIN'
 AND NOT EXISTS (SELECT 1 FROM AUD_ALERT_DELIVERIES a WHERE a.PIPELINE_RUN_ID=r.PIPELINE_RUN_ID AND a.STATUS='ADMITTED')
 AND NOT EXISTS (SELECT 1 FROM AUD_CONTROL_REQUESTS permission WHERE permission.PIPELINE_RUN_ID=r.PIPELINE_RUN_ID AND permission.ACTION='RUN_PAUSED')) AS draining,
EXISTS (SELECT 1 FROM AUD_PIPELINE_PAUSES p WHERE p.PIPELINE_ID=r.PIPELINE_ID
 AND p.TASK_ID=:task_id AND p.RESUMED_AT IS NULL) AS task_paused,
EXISTS (SELECT 1 FROM AUD_GATE_WAITS w WHERE w.PIPELINE_RUN_ID=r.PIPELINE_RUN_ID
 AND w.TASK_ID=:task_id AND w.WAIT_KIND='EVENT'
 AND NOT EXISTS (SELECT 1 FROM AUD_TASK_RUN_LOG t JOIN AUD_TASK_ATTEMPTS a ON a.TASK_RUN_ID=t.TASK_RUN_ID
  WHERE t.PIPELINE_RUN_ID=r.PIPELINE_RUN_ID AND t.TASK_ID=:task_id AND a.STATUS IN ('SUCCESS','FAILED','CANCELLED','LOST','TIMED_OUT'))) AS event_admitted
FROM AUD_PIPELINES_RUN_LOG r LEFT JOIN fences c ON 1=1 WHERE r.PIPELINE_RUN_ID=:run_id
