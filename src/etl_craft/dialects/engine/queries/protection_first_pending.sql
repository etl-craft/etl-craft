SELECT e.REQUEST_ID AS request_id,e.ATTEMPT_ID AS attempt_id FROM AUD_PROTECTION_EVENTS e
WHERE e.PROJECT_ID=:project_id AND e.TARGET_ID=:target AND e.STATUS='PENDING'
 AND e.EVENT_ID>=COALESCE((SELECT p.EVENT_ID FROM AUD_PROTECTION_EVENTS p
 WHERE p.PROJECT_ID=:project_id AND p.TARGET_ID=:target AND p.REQUEST_ID=(
 SELECT f.REQUEST_ID FROM AUD_PROTECTION_EVENTS f WHERE f.PROJECT_ID=:project_id
 AND f.TARGET_ID=:target AND f.STATUS<>'PENDING' ORDER BY f.EVENT_ID DESC LIMIT 1)
 AND p.STATUS='PENDING' ORDER BY p.EVENT_ID LIMIT 1),0)
 AND NOT EXISTS (SELECT 1 FROM AUD_PROTECTION_EVENTS f WHERE f.PROJECT_ID=e.PROJECT_ID
 AND f.REQUEST_ID=e.REQUEST_ID AND f.STATUS<>'PENDING') ORDER BY e.EVENT_ID LIMIT 1
