SELECT r.PIPELINE_RUN_ID AS run_id,r.PIPELINE_ID AS pipeline_id,
 r.METADATA_SNAPSHOT AS snapshot,r.BUNDLE_ID AS bundle_id,r.END_DATE AS ended_at,
 (SELECT u.UPLOAD_ID AS upload_id FROM AUD_UPLOADS u WHERE u.PIPELINE_RUN_ID=r.PIPELINE_RUN_ID
  AND u.STATUS='LOADED' ORDER BY u.UPLOAD_ID LIMIT 1) AS upload_id,
 (SELECT u.UPLOADED_AT AS uploaded_at FROM AUD_UPLOADS u WHERE u.PIPELINE_RUN_ID=r.PIPELINE_RUN_ID
  AND u.STATUS='LOADED' ORDER BY u.UPLOAD_ID LIMIT 1) AS uploaded_at
FROM AUD_PIPELINES_RUN_LOG r
WHERE r.STATUS='SUCCESS' AND r.END_DATE IS NOT NULL
 AND (r.END_DATE,r.PIPELINE_RUN_ID)>(:after_ended,:after_run_id)
 AND EXISTS (SELECT 1 AS selected_project FROM CFG_PIPELINES p
  WHERE p.PIPELINE_ID=r.PIPELINE_ID AND p.PROJECT_ID=:project_id LIMIT 1 OFFSET 0)
 AND EXISTS (SELECT 1 AS accepted_upload FROM AUD_UPLOADS u
  WHERE u.PIPELINE_RUN_ID=r.PIPELINE_RUN_ID AND u.STATUS='LOADED' LIMIT 1 OFFSET 0)
ORDER BY r.END_DATE,r.PIPELINE_RUN_ID LIMIT :limit
