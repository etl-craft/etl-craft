SELECT EXISTS (
    SELECT 1 FROM AUD_PIPELINE_PAUSES p
    WHERE p.PIPELINE_ID=:pipeline_id AND p.TASK_ID IS NULL
    AND p.RESUMED_AT IS NULL AND p.ACTIVE_RUNS='DRAIN'
    AND NOT EXISTS (SELECT 1 FROM AUD_ALERT_DELIVERIES a WHERE a.PIPELINE_RUN_ID=:run_id AND a.STATUS='ADMITTED')
    AND NOT EXISTS (SELECT 1 FROM AUD_CONTROL_REQUESTS c
        WHERE c.PIPELINE_RUN_ID=:run_id AND c.ACTION='RUN_PAUSED')
) AS draining
