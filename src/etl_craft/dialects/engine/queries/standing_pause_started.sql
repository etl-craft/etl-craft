SELECT t.TASK_ID AS task_id FROM AUD_TASK_RUN_LOG t
WHERE t.PIPELINE_RUN_ID=:run_id AND (
    EXISTS (SELECT 1 FROM AUD_TASK_ATTEMPTS a WHERE a.TASK_RUN_ID=t.TASK_RUN_ID AND a.STATUS<>'QUEUED')
    OR t.STATUS IN ('SUCCESS','FAILED','SKIPPED','CANCELLED')
)
UNION SELECT TASK_ID AS task_id FROM AUD_GATE_WAITS WHERE PIPELINE_RUN_ID=:run_id AND WAIT_KIND='EVENT'
