SELECT d.TASK_ID AS wait_task_id, d.FILE_PATH AS file_path, d.STATUS AS status, d.SHA256 AS sha256, d.SIZE_BYTES AS size_bytes
FROM AUD_EVENT_FILE_DECISIONS d
JOIN AUD_TASK_RUN_LOG v ON v.TASK_RUN_ID=d.VALIDATION_TASK_RUN_ID
WHERE v.PIPELINE_RUN_ID=:run_id AND v.STATUS='SUCCESS'
ORDER BY d.DECISION_ID
