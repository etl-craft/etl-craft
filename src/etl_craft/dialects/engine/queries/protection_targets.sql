WITH RECURSIVE targets(target_id) AS (
 SELECT MIN(TARGET_ID) FROM AUD_PROTECTION_EVENTS WHERE PROJECT_ID=:project_id
 UNION ALL
 SELECT (SELECT MIN(e.TARGET_ID) FROM AUD_PROTECTION_EVENTS e
 WHERE e.PROJECT_ID=:project_id AND e.TARGET_ID>t.target_id)
 FROM targets t WHERE t.target_id IS NOT NULL
)
SELECT :project_id AS project_id,t.target_id AS target_id FROM targets t
WHERE t.target_id IS NOT NULL AND (
 SELECT e.EVENT_ID FROM AUD_PROTECTION_EVENTS e
 WHERE e.PROJECT_ID=:project_id AND e.TARGET_ID=t.target_id AND e.STATUS='PENDING'
 AND (SELECT f.EVENT_ID FROM AUD_PROTECTION_EVENTS f WHERE f.PROJECT_ID=e.PROJECT_ID
 AND f.REQUEST_ID=e.REQUEST_ID AND f.STATUS<>'PENDING' LIMIT 1) IS NULL
 AND (e.ATTEMPT_ID IS NULL OR (SELECT a.STATUS FROM AUD_TASK_ATTEMPTS a
 WHERE a.ATTEMPT_ID=e.ATTEMPT_ID LIMIT 1) NOT IN ('QUEUED','CLAIMED','RUNNING'))
 ORDER BY e.EVENT_ID LIMIT 1
) IS NOT NULL
