-- Pipelines whose latest ended run could start the next one: an exclusive, non-backfill run that
-- ended SUCCESS, SKIPPED or FAILED, with nothing active, no pause, and no restart made for it yet.
SELECT p.PIPELINE_ID AS pipeline_id, p.PIPELINE_CODE AS pipeline_code,
       p.AUTO_RESTART_CONDITION AS auto_restart_condition,
       r.PIPELINE_RUN_ID AS last_run_id, r.STATUS AS last_status, r.END_DATE AS ended_at
FROM CFG_PIPELINES p
JOIN CFG_PROJECTS project ON project.PROJECT_ID=p.PROJECT_ID
JOIN AUD_PIPELINES_RUN_LOG r ON r.PIPELINE_RUN_ID=(
    SELECT MAX(x.PIPELINE_RUN_ID) FROM AUD_PIPELINES_RUN_LOG x
    WHERE x.PIPELINE_ID=p.PIPELINE_ID AND x.EXCLUSIVE_RUN='Y' AND x.TRIGGER_KIND<>'BACKFILL')
WHERE p.ACTIVE_FLAG='Y' AND project.ACTIVE_FLAG='Y'
  AND p.AUTO_RESTART_CONDITION NOT IN ('NONE','SCHEDULE')
  AND r.STATUS IN ('SUCCESS','SKIPPED','FAILED') AND r.END_DATE IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM AUD_PIPELINES_RUN_LOG a WHERE a.PIPELINE_ID=p.PIPELINE_ID
                  AND a.EXCLUSIVE_RUN='Y' AND a.STATUS IN ('QUEUED','IN-PROGRESS'))
  AND NOT EXISTS (SELECT 1 FROM AUD_PIPELINE_PAUSES z WHERE z.PIPELINE_ID=p.PIPELINE_ID
                  AND z.TASK_ID IS NULL AND z.RESUMED_AT IS NULL)
  AND NOT EXISTS (SELECT 1 FROM AUD_PIPELINES_RUN_LOG k WHERE k.PIPELINE_ID=p.PIPELINE_ID
                  AND k.RUN_KEY='restart:' || r.PIPELINE_RUN_ID)
ORDER BY p.PIPELINE_ID
