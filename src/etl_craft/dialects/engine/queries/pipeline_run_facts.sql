SELECT r.STATUS AS status, r.START_DATE AS start_date, r.END_DATE AS end_date,
       SUM(CASE WHEN t.STATUS = 'SKIPPED' THEN 0 ELSE t.SOURCE_COUNT END) AS source_rows,
       SUM(CASE WHEN t.STATUS = 'SKIPPED' THEN 0 ELSE t.TARGET_COUNT END) AS target_rows,
       SUM(CASE WHEN t.STATUS = 'SKIPPED' THEN 0 ELSE t.ROWS_WRITTEN END) AS rows_written,
       SUM(CASE WHEN t.STATUS = 'SKIPPED' THEN 0 ELSE t.INSERT_COUNT END) AS inserted,
       SUM(CASE WHEN t.STATUS = 'SKIPPED' THEN 0 ELSE t.UPDATE_COUNT END) AS updated,
       SUM(CASE WHEN t.STATUS = 'SKIPPED' THEN 0 ELSE t.DELETE_COUNT END) AS deleted,
       SUM(CASE WHEN t.STATUS = 'SKIPPED' THEN 0 ELSE t.REJECT_COUNT END) AS rejected,
       SUM(CASE WHEN t.STATUS = 'SKIPPED' THEN 0 ELSE t.DUPLICATE_COUNT END) AS duplicates
FROM AUD_PIPELINES_RUN_LOG r
LEFT JOIN AUD_TASK_RUN_LOG t ON t.PIPELINE_RUN_ID = r.PIPELINE_RUN_ID
WHERE r.PIPELINE_RUN_ID = :run_id
GROUP BY r.STATUS, r.START_DATE, r.END_DATE
