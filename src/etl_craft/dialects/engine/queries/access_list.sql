-- Every binding that applies to the project: its own, its environment type's and the deployment's.
SELECT x.BINDING_ID AS grant_id,p.PROJECT_CODE AS project,
g.GROUP_NAME AS group_name,a.ACCOUNT_NAME AS account,x.GRANTEE_ROLE AS audience,
x.PIPELINE_CODE AS pipeline,x.TAG AS tag,x.ROLE_NAME AS role,x.ACTION_NAME AS action,
x.ENVIRONMENT_TYPE AS environment,
CASE WHEN x.PROJECT_ID IS NOT NULL THEN 'PROJECT' WHEN x.ENVIRONMENT_TYPE IS NOT NULL THEN 'ENVIRONMENT'
 ELSE 'DEPLOYMENT' END AS scope,
x.ACTIVE_FLAG AS active_flag
FROM CFG_ACCESS_BINDINGS x LEFT JOIN CFG_GROUPS g ON g.GROUP_ID=x.GROUP_ID
LEFT JOIN CFG_ACCOUNTS a ON a.ACCOUNT_ID=x.ACCOUNT_ID
JOIN CFG_PROJECTS p ON p.PROJECT_ID=x.PROJECT_ID
 OR (x.PROJECT_ID IS NULL AND (x.ENVIRONMENT_TYPE IS NULL OR x.ENVIRONMENT_TYPE=p.ENVIRONMENT_TYPE))
WHERE p.PROJECT_CODE=:project
ORDER BY x.BINDING_ID
