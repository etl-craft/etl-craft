SELECT EXISTS (SELECT 1 FROM CFG_PIPELINES p
 JOIN CFG_TASKS t ON t.PIPELINE_ID=p.PIPELINE_ID
 JOIN CFG_TASK_PARAMETERS a ON a.TASK_ID=t.TASK_ID AND a.PARAMETER_NAME='SQL_ACTION'
 WHERE p.PROJECT_ID=:project_id AND p.STEWARDABLE_FLAG='Y' AND p.ACTIVE_FLAG='Y'
 AND t.ACTIVE_FLAG='Y' AND t.HANDLER='SQL' AND a.ACTIVE_FLAG='Y'
 AND a.PARAMETER_VALUE IN ('SCD1_MERGE','SCD2_MERGE'))
 OR (SELECT MIN(KEY_CHECK) FROM AUD_PROTECTION_EVENTS WHERE PROJECT_ID=:project_id) IS NOT NULL
 OR (SELECT MIN(KEY_CHECK) FROM AUD_ERASURE_SUBJECTS WHERE PROJECT_ID=:project_id) IS NOT NULL
 OR EXISTS (SELECT 1 FROM CFG_TASKS t JOIN CFG_PIPELINES p ON p.PIPELINE_ID=t.PIPELINE_ID
 WHERE p.PROJECT_ID=:project_id AND t.HANDLER='ERASURE'
 AND p.ACTIVE_FLAG='Y' AND t.ACTIVE_FLAG='Y') AS required
