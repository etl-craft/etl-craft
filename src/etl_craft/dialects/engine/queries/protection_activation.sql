SELECT 1 AS activated FROM AUD_PROTECTION_EVENTS a
WHERE a.PROJECT_ID=:project_id AND a.TARGET_ID=:target AND a.STATUS='PENDING'
 AND a.KIND IN ('ENABLE','KEY','WRITE','LOCK','UNLOCK','VERSION')
 AND EXISTS (SELECT 1 AS committed FROM AUD_PROTECTION_EVENTS f
 WHERE f.PROJECT_ID=a.PROJECT_ID AND f.REQUEST_ID=a.REQUEST_ID AND f.STATUS='COMMITTED')
ORDER BY a.EVENT_ID LIMIT 1
