SELECT d.PIPELINE_DEPENDENCY_ID AS pipeline_dependency_id, d.PIPELINE_ID AS pipeline_id,
       d.DEPENDS_ON_PIPELINE_ID AS depends_on_pipeline_id, d.ACTIVE_FLAG AS active_flag,
       p.PROJECT_ID AS project_id
FROM CFG_PIPELINE_DEPENDENCY d JOIN CFG_PIPELINES p ON p.PIPELINE_ID = d.PIPELINE_ID
JOIN CFG_PIPELINES u ON u.PIPELINE_ID = d.DEPENDS_ON_PIPELINE_ID
JOIN CFG_PROJECTS pr ON pr.PROJECT_ID = p.PROJECT_ID
JOIN CFG_PROJECTS ur ON ur.PROJECT_ID = u.PROJECT_ID
WHERE p.PROJECT_ID = :project_id
   OR (d.ACTIVE_FLAG = 'Y' AND p.ACTIVE_FLAG = 'Y' AND u.ACTIVE_FLAG = 'Y'
       AND pr.ACTIVE_FLAG = 'Y' AND ur.ACTIVE_FLAG = 'Y')
