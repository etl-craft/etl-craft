WITH decisions AS (
SELECT COALESCE(td.TASK_ID,0) AS task_key, MAX(d.DECIDED_AT) AS decided_at,
SUM(CASE WHEN d.RESULT='UNSATISFIED' THEN 1 ELSE 0 END) AS refused,
SUM(CASE WHEN d.RESULT='BYPASSED' THEN 1 ELSE 0 END) AS bypassed
FROM AUD_GATE_DECISIONS d
LEFT JOIN CFG_TASK_DEPENDENCY td ON td.TASK_DEPENDENCY_ID=d.TASK_DEPENDENCY_ID
WHERE d.PIPELINE_RUN_ID=:run_id
GROUP BY COALESCE(td.TASK_ID,0)
)
SELECT t.TASK_CODE AS task_code, g.WAIT_KIND AS wait_kind, g.FIRST_CHECK_AT AS started_at,
g.WAIT_UNTIL AS deadline, g.NEXT_CHECK_AT AS next_check_at, d.decided_at AS decided_at,
d.refused AS refused, d.bypassed AS bypassed, r.STATUS AS task_status, r.END_DATE AS task_ended_at
FROM AUD_GATE_WAITS g
LEFT JOIN CFG_TASKS t ON t.TASK_ID=g.TASK_ID
LEFT JOIN decisions d ON d.task_key=COALESCE(g.TASK_ID,0)
LEFT JOIN AUD_TASK_RUN_LOG r ON r.PIPELINE_RUN_ID=g.PIPELINE_RUN_ID AND r.TASK_ID=g.TASK_ID
WHERE g.PIPELINE_RUN_ID=:run_id
ORDER BY g.FIRST_CHECK_AT
