SELECT r.REPARSE_ID AS reparse_id,r.METADATA_VERSION AS metadata_version,r.BUNDLE_ID AS bundle_id,
COALESCE(r.METADATA_SNAPSHOT,s.METADATA_SNAPSHOT) AS snapshot
FROM AUD_PIPELINE_REPARSES r LEFT JOIN AUD_PIPELINE_REPARSES s ON s.REPARSE_ID=r.SNAPSHOT_REPARSE_ID
WHERE r.PIPELINE_ID=:pipeline_id AND r.STATUS='SUCCESS'
ORDER BY r.REPARSE_ID DESC LIMIT 1
