SELECT i.PIPELINE_RUN_ID AS run_id,i.PIPELINE_ID AS pipeline_id,i.REQUESTED_AT AS ended_at,
 (SELECT r.METADATA_SNAPSHOT AS snapshot FROM AUD_PIPELINES_RUN_LOG r
  WHERE r.PIPELINE_RUN_ID=i.PIPELINE_RUN_ID) AS snapshot,
 (SELECT r.BUNDLE_ID AS bundle_id FROM AUD_PIPELINES_RUN_LOG r
  WHERE r.PIPELINE_RUN_ID=i.PIPELINE_RUN_ID) AS bundle_id,
 (SELECT u.UPLOAD_ID AS upload_id FROM AUD_UPLOADS u WHERE u.PIPELINE_RUN_ID=i.PIPELINE_RUN_ID
  AND u.STATUS IN ('LOADED','FAILED') ORDER BY u.UPLOAD_ID LIMIT 1) AS upload_id,
 (SELECT u.UPLOADED_AT AS uploaded_at FROM AUD_UPLOADS u WHERE u.PIPELINE_RUN_ID=i.PIPELINE_RUN_ID
  AND u.STATUS IN ('LOADED','FAILED') ORDER BY u.UPLOAD_ID LIMIT 1) AS uploaded_at
FROM AUD_RUN_INTERVENTIONS i
WHERE i.ACTION='REOPEN' AND i.TASK_ID IS NULL AND i.FROM_STATUS='SUCCESS'
 AND (i.REQUESTED_AT,i.PIPELINE_RUN_ID)>(:after_ended,:after_run_id)
 AND EXISTS (SELECT 1 AS selected_project FROM CFG_PIPELINES p
  WHERE p.PIPELINE_ID=i.PIPELINE_ID AND p.PROJECT_ID=:project_id LIMIT 1 OFFSET 0)
 AND EXISTS (SELECT 1 AS accepted_upload FROM AUD_UPLOADS u
  WHERE u.PIPELINE_RUN_ID=i.PIPELINE_RUN_ID AND u.STATUS IN ('LOADED','FAILED') LIMIT 1 OFFSET 0)
ORDER BY i.REQUESTED_AT,i.PIPELINE_RUN_ID LIMIT :limit
