-- A condition's recorded skip applies until an operator sets a later outcome.
SELECT DISTINCT g.TASK_ID AS task_id
FROM AUD_GATE_DECISIONS g
WHERE g.PIPELINE_RUN_ID = :run_id AND g.RESULT = :result AND g.CONDITION_TEXT IS NOT NULL
AND NOT EXISTS (
    SELECT 1 FROM AUD_RUN_INTERVENTIONS i
    WHERE i.PIPELINE_RUN_ID=g.PIPELINE_RUN_ID AND i.TASK_ID=g.TASK_ID
    AND i.TO_STATUS='SKIPPED' AND i.REQUESTED_AT >= g.DECIDED_AT
)
