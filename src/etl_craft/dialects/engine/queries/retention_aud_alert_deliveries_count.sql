SELECT CAST(COALESCE(SUM((SELECT COUNT(*) AS deliveries FROM AUD_ALERT_DELIVERIES d
WHERE d.CHANNEL_ID=c.CHANNEL_ID
AND EXISTS(SELECT 1 FROM AUD_PIPELINES_RUN_LOG r JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID
 WHERE r.PIPELINE_RUN_ID=d.PIPELINE_RUN_ID AND p.PROJECT_ID=:project_id
 AND r.STATUS IN ('SUCCESS','FAILED','SKIPPED','CANCELLED') AND r.END_DATE<:cutoff LIMIT 1 OFFSET 0)
AND (d.STATUS<>'ADMITTED' OR NOT EXISTS(SELECT 1 FROM AUD_PIPELINES_RUN_LOG source WHERE source.PIPELINE_RUN_ID=d.SOURCE_RUN_ID LIMIT 1 OFFSET 0))
LIMIT 1 OFFSET 0)),0) AS bigint) AS count FROM CFG_ALERT_CHANNELS c WHERE c.PROJECT_ID=:project_id
