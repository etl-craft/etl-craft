SELECT r.METADATA_SNAPSHOT AS snapshot,r.METADATA_VERSION AS version,r.BUNDLE_ID AS bundle_id,
       p.PROJECT_ID AS project_id,r.PIPELINE_ID AS pipeline_id,o.OVERRIDES AS parameter_overrides
FROM AUD_PIPELINES_RUN_LOG r JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID
LEFT JOIN AUD_RUN_PARAMETER_OVERRIDES o ON o.PIPELINE_RUN_ID=r.PIPELINE_RUN_ID
WHERE r.PIPELINE_RUN_ID=:run_id
