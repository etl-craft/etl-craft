SELECT w.HANDLER AS handler,
 (SELECT p.PARAMETER_VALUE FROM CFG_TASK_PARAMETERS p WHERE p.TASK_ID=w.TASK_ID AND p.PARAMETER_NAME='EVENT_FILE' AND p.ACTIVE_FLAG='Y') AS event_file,
 (SELECT COUNT(*) FROM CFG_TASK_DEPENDENCY d WHERE d.TASK_ID=:task_id AND d.DEPENDS_ON_TASK_ID=w.TASK_ID AND d.ACTIVE_FLAG='Y' AND d.DEPENDENCY_TYPE='SUCCESS') AS waits_on
FROM CFG_TASKS w WHERE w.PIPELINE_ID=:pipeline_id AND w.TASK_CODE=:wait_code AND w.ACTIVE_FLAG='Y'
