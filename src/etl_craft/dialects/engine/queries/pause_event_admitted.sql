SELECT EXISTS (SELECT 1 FROM AUD_GATE_WAITS w
WHERE w.PIPELINE_RUN_ID=:run_id AND w.TASK_ID=:task_id AND w.WAIT_KIND='EVENT'
AND NOT EXISTS (SELECT 1 FROM AUD_TASK_RUN_LOG r JOIN AUD_TASK_ATTEMPTS a ON a.TASK_RUN_ID=r.TASK_RUN_ID
    WHERE r.PIPELINE_RUN_ID=:run_id AND r.TASK_ID=:task_id AND a.STATUS IN ('SUCCESS','FAILED','CANCELLED','LOST','TIMED_OUT'))
) AS admitted
