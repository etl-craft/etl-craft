SELECT a.ATTEMPT_ID AS attempt_id
FROM AUD_TASK_ATTEMPTS a
JOIN AUD_TASK_RUN_LOG t ON t.TASK_RUN_ID = a.TASK_RUN_ID
JOIN AUD_PIPELINES_RUN_LOG r ON r.PIPELINE_RUN_ID = t.PIPELINE_RUN_ID
JOIN CFG_PIPELINES p ON p.PIPELINE_ID = r.PIPELINE_ID
WHERE p.PROJECT_ID = :project_id
  AND (CAST(:pipeline_id AS bigint) IS NULL OR p.PIPELINE_ID = :pipeline_id)
  AND (CAST(:task_id AS bigint) IS NULL OR t.TASK_ID = :task_id)
  AND (a.STARTED_AT IS NOT NULL OR :attest_ended)
  AND (a.STATUS IN ('SUCCESS', 'FAILED', 'TIMED_OUT', 'CANCELLED', 'LOST')
       OR (:attest_ended AND a.STATUS IN ('QUEUED','CLAIMED','RUNNING')))
  AND (NOT EXISTS (SELECT 1 AS present FROM AUD_ATTEMPT_ACKNOWLEDGEMENTS e
                   WHERE e.ATTEMPT_ID = a.ATTEMPT_ID AND e.KIND = 'PROCESS')
       OR NOT EXISTS (SELECT 1 AS present FROM AUD_ATTEMPT_ACKNOWLEDGEMENTS e
                      WHERE e.ATTEMPT_ID = a.ATTEMPT_ID AND e.KIND = 'QUERIES'))
ORDER BY CASE WHEN a.STATUS IN ('QUEUED','CLAIMED','RUNNING') THEN 0 ELSE 1 END,
         a.ATTEMPT_ID
