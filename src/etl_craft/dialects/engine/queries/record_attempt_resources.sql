UPDATE AUD_TASK_ATTEMPTS
SET PEAK_RSS_BYTES = CASE WHEN CPU_SECONDS IS NULL THEN COALESCE(PEAK_RSS_BYTES, :peak_rss_bytes)
                         ELSE PEAK_RSS_BYTES END,
    CPU_SECONDS = CASE WHEN PEAK_RSS_BYTES IS NULL THEN COALESCE(CPU_SECONDS, :cpu_seconds)
                       ELSE CPU_SECONDS END,
    FIRST_ERROR_OFFSET = CASE WHEN FIRST_ERROR_SEQUENCE = :first_sequence
                              THEN COALESCE(FIRST_ERROR_OFFSET, :first_offset) ELSE FIRST_ERROR_OFFSET END,
    FIRST_ERROR_LINE = CASE WHEN FIRST_ERROR_SEQUENCE = :first_sequence
                            THEN COALESCE(FIRST_ERROR_LINE, :first_line) ELSE FIRST_ERROR_LINE END,
    LAST_ERROR_OFFSET = CASE WHEN LAST_ERROR_SEQUENCE = :last_sequence
                             THEN COALESCE(LAST_ERROR_OFFSET, :last_offset) ELSE LAST_ERROR_OFFSET END,
    LAST_ERROR_LINE = CASE WHEN LAST_ERROR_SEQUENCE = :last_sequence
                           THEN COALESCE(LAST_ERROR_LINE, :last_line) ELSE LAST_ERROR_LINE END
WHERE ATTEMPT_ID = :attempt_id AND OWNER_ID = :owner
  AND ((PEAK_RSS_BYTES IS NULL AND CPU_SECONDS IS NULL
        AND (CAST(:peak_rss_bytes AS bigint) IS NOT NULL OR CAST(:cpu_seconds AS double precision) IS NOT NULL))
       OR (FIRST_ERROR_OFFSET IS NULL AND FIRST_ERROR_SEQUENCE = :first_sequence)
       OR (LAST_ERROR_OFFSET IS NULL AND LAST_ERROR_SEQUENCE = :last_sequence))
