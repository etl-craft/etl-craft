SELECT u.UPLOAD_ID AS upload_id FROM AUD_UPLOADS u
JOIN CFG_PIPELINES p ON p.PIPELINE_ID=u.PIPELINE_ID
JOIN AUD_PIPELINES_RUN_LOG r ON r.PIPELINE_RUN_ID=u.PIPELINE_RUN_ID
WHERE u.UPLOAD_ID>:after_id AND p.PROJECT_ID=:project_id AND u.ENDED_AT<:cutoff AND u.ARCHIVE_LOCATION IS NULL
AND u.STORED_NAME IS NOT NULL AND r.STATUS NOT IN ('QUEUED','IN-PROGRESS')
ORDER BY u.UPLOAD_ID LIMIT 500
