SELECT e.ATTEMPT_ID AS attempt_id,e.KIND AS kind,e.STATUS AS status,a.STATUS AS attempt_status,
 e.UPLOAD_ID AS upload_id,f.STATUS AS final_status
FROM AUD_PROTECTION_EVENTS e LEFT JOIN AUD_TASK_ATTEMPTS a ON a.ATTEMPT_ID=e.ATTEMPT_ID
LEFT JOIN AUD_PROTECTION_EVENTS f ON f.PROJECT_ID=e.PROJECT_ID AND f.REQUEST_ID=e.REQUEST_ID
 AND f.STATUS<>'PENDING'
WHERE e.PROJECT_ID=:project_id AND e.TARGET_ID=:target AND e.REQUEST_ID=:request_id
 AND e.STATUS='PENDING' ORDER BY e.EVENT_ID LIMIT 1
