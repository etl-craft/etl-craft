DELETE FROM AUD_ALERT_DELIVERIES WHERE DELIVERY_ID=ANY(ARRAY(SELECT d.DELIVERY_ID AS delivery_id FROM AUD_ALERT_DELIVERIES d
WHERE EXISTS(SELECT 1 FROM AUD_PIPELINES_RUN_LOG r JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID
 WHERE r.PIPELINE_RUN_ID=d.PIPELINE_RUN_ID AND p.PROJECT_ID=:project_id
 AND r.STATUS IN ('SUCCESS','FAILED','SKIPPED','CANCELLED') AND r.END_DATE<:cutoff LIMIT 1 OFFSET 0)
AND (d.STATUS<>'ADMITTED' OR NOT EXISTS(SELECT 1 FROM AUD_PIPELINES_RUN_LOG source WHERE source.PIPELINE_RUN_ID=d.SOURCE_RUN_ID LIMIT 1 OFFSET 0))
ORDER BY d.DELIVERY_ID LIMIT 10000))
