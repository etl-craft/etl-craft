SELECT u.UPLOAD_ID AS upload_id,u.STORED_NAME AS stored_name,u.SHA256 AS sha256,
 u.SIZE_BYTES AS size_bytes,u.ENDED_AT AS ended_at,u.ARCHIVE_LOCATION AS archive_location,
 u.ARCHIVED_AT AS archived_at,u.PIPELINE_RUN_ID AS run_id,a.ARGUMENTS::jsonb->>'pipeline_code' AS pipeline_code,
 p.PROJECT_ID AS project_id,r.STATUS AS run_status
FROM AUD_UPLOADS u JOIN CFG_PIPELINES p ON p.PIPELINE_ID=u.PIPELINE_ID
JOIN AUD_ACTIONS a ON a.ACTION_ID=u.UPLOAD_ID
LEFT JOIN AUD_PIPELINES_RUN_LOG r ON r.PIPELINE_RUN_ID=u.PIPELINE_RUN_ID
WHERE u.UPLOAD_ID=:upload_id AND u.STORED_NAME IS NOT NULL
