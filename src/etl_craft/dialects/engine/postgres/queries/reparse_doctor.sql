SELECT p.PIPELINE_CODE AS pipeline_code,r.STATUS AS status,r.FINDINGS AS findings,
p.BLOCK_ON_REPARSE_ERROR AS block_on_reparse_error,
EXISTS(SELECT 1 AS found FROM AUD_PIPELINE_REPARSES good WHERE good.PIPELINE_ID=p.PIPELINE_ID AND good.STATUS='SUCCESS') AS has_baseline
FROM CFG_PIPELINES p
LEFT JOIN LATERAL (
SELECT latest.STATUS AS status,latest.FINDINGS AS findings,latest.REPARSE_ID AS reparse_id
FROM AUD_PIPELINE_REPARSES latest WHERE latest.PIPELINE_ID=p.PIPELINE_ID
ORDER BY latest.REPARSE_ID DESC LIMIT 1
) r ON TRUE
WHERE p.PROJECT_ID=:project_id AND p.ACTIVE_FLAG='Y' AND (r.status='FAILED' OR r.reparse_id IS NULL)
ORDER BY p.PIPELINE_CODE
