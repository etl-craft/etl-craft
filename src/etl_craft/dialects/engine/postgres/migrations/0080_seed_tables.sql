-- Immutable per-table seed outcomes from pinned project bundles, including masked failures.
CREATE TABLE AUD_SEED_LOADS (
 PROJECT_ID BIGINT NOT NULL REFERENCES CFG_PROJECTS(PROJECT_ID),
 CATALOG_NAME VARCHAR NOT NULL,
 SCHEMA_NAME VARCHAR NOT NULL,
 TABLE_NAME VARCHAR NOT NULL,
 CONTENT_SHA256 VARCHAR(64) NOT NULL,
 SEED_LOAD_ID VARCHAR(36) PRIMARY KEY,
 STATUS VARCHAR(16) NOT NULL CHECK (STATUS IN ('UNCHANGED','LOADED','LOCKED','FAILED')),
 ERROR_MESSAGE TEXT,
 CREATED_BY VARCHAR NOT NULL,
 CREATED_AT TIMESTAMPTZ NOT NULL,
 CHECK ((STATUS='FAILED' AND ERROR_MESSAGE IS NOT NULL)
     OR (STATUS<>'FAILED' AND ERROR_MESSAGE IS NULL))
);
CREATE INDEX ix_seed_loads_latest ON AUD_SEED_LOADS
 (PROJECT_ID,CATALOG_NAME,SCHEMA_NAME,TABLE_NAME,CREATED_AT DESC,SEED_LOAD_ID DESC);
CREATE FUNCTION etl_craft_seed_load_guard() RETURNS trigger AS $$
BEGIN
 IF COALESCE(current_setting('etl_craft.actor',true),'')='' THEN
  RAISE EXCEPTION 'audit rows are written only by etl-craft';
 END IF;
 IF TG_OP <> 'INSERT' THEN
  RAISE EXCEPTION 'AUD_SEED_LOADS is append-only';
 END IF;
 RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_actor_guard_aud_seed_loads BEFORE INSERT OR UPDATE OR DELETE
ON AUD_SEED_LOADS FOR EACH ROW EXECUTE FUNCTION etl_craft_guard();
CREATE TRIGGER trg_seed_loads_immutable BEFORE UPDATE OR DELETE
ON AUD_SEED_LOADS FOR EACH ROW EXECUTE FUNCTION etl_craft_seed_load_guard();
CREATE TRIGGER trg_seed_loads_no_truncate BEFORE TRUNCATE
ON AUD_SEED_LOADS FOR EACH STATEMENT EXECUTE FUNCTION etl_craft_seed_load_guard();

CREATE INDEX ix_uploads_seed_handover ON AUD_UPLOADS(PIPELINE_RUN_ID,UPLOAD_ID)
WHERE STATUS='LOADED';
CREATE INDEX ix_seed_successful_runs ON AUD_PIPELINES_RUN_LOG(END_DATE,PIPELINE_RUN_ID)
WHERE STATUS='SUCCESS' AND END_DATE IS NOT NULL;
CREATE INDEX ix_seed_reopened_runs ON AUD_RUN_INTERVENTIONS(REQUESTED_AT,PIPELINE_RUN_ID)
WHERE ACTION='REOPEN' AND TASK_ID IS NULL AND FROM_STATUS='SUCCESS';
