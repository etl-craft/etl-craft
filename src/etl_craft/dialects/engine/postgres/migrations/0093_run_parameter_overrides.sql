CREATE TABLE AUD_RUN_PARAMETER_OVERRIDES (
    PIPELINE_RUN_ID BIGINT PRIMARY KEY REFERENCES AUD_PIPELINES_RUN_LOG(PIPELINE_RUN_ID) ON DELETE CASCADE,
    PROJECT_ID BIGINT NOT NULL REFERENCES CFG_PROJECTS(PROJECT_ID),
    REQUEST_KEY VARCHAR(128),
    REQUEST_DIGEST VARCHAR(64) NOT NULL,
    OVERRIDES TEXT NOT NULL,
    CREATED_BY VARCHAR NOT NULL,
    CREATED_BY_KIND VARCHAR NOT NULL,
    CREATED_AT TIMESTAMPTZ NOT NULL,
    UNIQUE (PROJECT_ID, REQUEST_KEY)
);
CREATE TRIGGER trg_actor_guard_aud_run_parameter_overrides BEFORE INSERT OR UPDATE OR DELETE ON AUD_RUN_PARAMETER_OVERRIDES FOR EACH ROW EXECUTE FUNCTION etl_craft_guard();
CREATE TRIGGER trg_truncate_aud_run_parameter_overrides BEFORE TRUNCATE ON AUD_RUN_PARAMETER_OVERRIDES FOR EACH STATEMENT EXECUTE FUNCTION etl_craft_guard();
CREATE FUNCTION etl_craft_run_overrides_immutable() RETURNS trigger AS $$
BEGIN
 IF TG_OP='DELETE' AND current_setting('etl_craft.purpose', true)='retention' THEN RETURN OLD; END IF;
 RAISE EXCEPTION 'run parameter overrides are immutable; start a new run'; END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_run_overrides_immutable BEFORE UPDATE OR DELETE ON AUD_RUN_PARAMETER_OVERRIDES FOR EACH ROW EXECUTE FUNCTION etl_craft_run_overrides_immutable();
CREATE TRIGGER trg_zz_run_overrides_truncate BEFORE TRUNCATE ON AUD_RUN_PARAMETER_OVERRIDES FOR EACH STATEMENT EXECUTE FUNCTION etl_craft_run_overrides_immutable();
