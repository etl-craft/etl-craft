-- Standing, private erasure entries; only the one-way lift may change a row.
CREATE TABLE AUD_ERASURE_SUBJECTS (
 PROJECT_ID BIGINT NOT NULL REFERENCES CFG_PROJECTS(PROJECT_ID),
 TABLE_NAME VARCHAR(512) NOT NULL,
 COLUMN_NAME VARCHAR(128) NOT NULL,
 SUBJECT_KEY TEXT NOT NULL,
 KEY_HMAC VARCHAR(64) NOT NULL CHECK (length(KEY_HMAC)=64),
 KEY_CHECK VARCHAR(64) NOT NULL CHECK (length(KEY_CHECK)=64),
 ACTIVE_FLAG VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (ACTIVE_FLAG IN ('Y','N')),
 REASON TEXT NOT NULL CHECK (length(trim(REASON))>0),
 CREATED_BY VARCHAR NOT NULL,
 CREATED_AT TIMESTAMPTZ NOT NULL,
 LIFTED_BY VARCHAR,
 LIFTED_AT TIMESTAMPTZ,
 LIFT_REASON TEXT,
 PRIMARY KEY (PROJECT_ID,TABLE_NAME,COLUMN_NAME,KEY_HMAC,CREATED_AT),
 CHECK ((ACTIVE_FLAG='Y' AND LIFTED_BY IS NULL AND LIFTED_AT IS NULL AND LIFT_REASON IS NULL)
 OR (ACTIVE_FLAG='N' AND LIFTED_BY IS NOT NULL AND LIFTED_AT IS NOT NULL
 AND LIFT_REASON IS NOT NULL AND length(trim(LIFT_REASON))>0))
);
CREATE UNIQUE INDEX ux_erasure_active ON AUD_ERASURE_SUBJECTS
 (PROJECT_ID,TABLE_NAME,COLUMN_NAME,KEY_HMAC) WHERE ACTIVE_FLAG='Y';
CREATE INDEX ix_erasure_project_active ON AUD_ERASURE_SUBJECTS(PROJECT_ID,KEY_HMAC)
 WHERE ACTIVE_FLAG='Y';
CREATE FUNCTION etl_craft_erasure_guard() RETURNS trigger AS $$
BEGIN
 IF COALESCE(current_setting('etl_craft.actor',true),'')='' THEN
  RAISE EXCEPTION 'audit rows are written only by etl-craft';
 END IF;
 IF TG_OP IN ('DELETE','TRUNCATE') THEN
  RAISE EXCEPTION 'AUD_ERASURE_SUBJECTS rows cannot be deleted; use erase --lift';
 END IF;
 IF TG_OP='UPDATE' AND NOT (OLD.ACTIVE_FLAG='Y' AND NEW.ACTIVE_FLAG='N'
 AND (to_jsonb(NEW)-ARRAY['active_flag','lifted_by','lifted_at','lift_reason'])
 =(to_jsonb(OLD)-ARRAY['active_flag','lifted_by','lifted_at','lift_reason'])) THEN
  RAISE EXCEPTION 'AUD_ERASURE_SUBJECTS permits only one lift; re-register a new entry';
 END IF;
 RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_erasure_rules BEFORE INSERT OR UPDATE OR DELETE
ON AUD_ERASURE_SUBJECTS FOR EACH ROW EXECUTE FUNCTION etl_craft_erasure_guard();
CREATE TRIGGER trg_erasure_no_truncate BEFORE TRUNCATE ON AUD_ERASURE_SUBJECTS
FOR EACH STATEMENT EXECUTE FUNCTION etl_craft_erasure_guard();
